def body(seqs, name, idx):
    return list(seqs[name]["entries"][idx]["body"])

def addr(seqs, name):
    return "@" + seqs[name]["addr"]

out = []
def emit(s=""):
    out.append(s)

def script(lines, comment=""):
    emit("  script" + (f"                                 ; {comment}" if comment else ""))
    for l in lines:
        emit(("      " if re.match(r"^\w+:$", l) else "        ") + l)

def text(speaker, s):
    emit(f'  text {speaker} "{s}"')

def stockseq(seqs, name, a, b, comment=""):
    emit(f"  stockseq {addr(seqs, name)} {a} {b}" + (f"    ; {comment}" if comment else ""))

