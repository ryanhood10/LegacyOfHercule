"""The mother dinosaur of the generator's eggs and her babies (zone 8 area 50, data/story/ch4_eggs.*; Ryan, 2026-11-04: "just recolour the king, make him pink and green and orange"; "the normal
tricerotops model ... with same colors as mom"): King Triceratops' record (sprite 127, 64 x 64, 7 groups) and a normal triceratops' (125, 32 x 32) with every frame recoloured, built from the ROM at
build time. Emits C source compiled into the co-op ROM; nothing from the ROM is committed.

usage: dinosprites.py roms/log2.gba build/gen/dino_sprites_data.c [--preview-dir build/x]

The hide's brown ramp keeps its shading and takes a colour by height in the body's box: the top (the frill and the back) pink, the middle orange, the feet green. Horns, eyes and outlines (greys, black, white) stay.
Colours are the game's one OBJ palette's, the nearest to each target."""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import sprites as S  # noqa: E402
from brolysprites import CWriter  # noqa: E402

RECORDS = ((127, "dino"), (125, "dino_baby"))
HIDE = (18, 19, 20, 21, 22, 23, 113)  # the browns of both, lightest first
TOP_END, MIDDLE_END = 0.36, 0.74      # fractions of the body's height
RAMPS = {
    "pink": ((255, 215, 235), (255, 190, 225), (248, 140, 200), (235, 100, 175), (205, 70, 145), (160, 50, 110), (105, 30, 75)),
    "orange": ((255, 225, 150), (255, 200, 100), (255, 160, 40), (240, 125, 15), (213, 98, 0), (172, 74, 0), (110, 45, 0)),
    "green": ((190, 245, 160), (150, 235, 120), (105, 215, 90), (70, 185, 70), (45, 150, 55), (30, 115, 40), (15, 70, 25)),
}


def nearest(pal, rgb):
    best, bd = None, 1 << 30
    for i in range(2, 256):
        r, g, b = pal[i]
        d = (r - rgb[0]) ** 2 + (g - rgb[1]) ** 2 + (b - rgb[2]) ** 2
        if d < bd:
            best, bd = i, d
    return best


def recolour(px, maps):
    ys = [y for y, row in enumerate(px) if any(row)]
    if not ys:
        return px
    top, height = ys[0], max(1, ys[-1] - ys[0] + 1)
    out = []
    for y, row in enumerate(px):
        f = (y - top) / height
        m = maps["pink"] if f < TOP_END else maps["orange"] if f < MIDDLE_END else maps["green"]
        out.append([m.get(v, v) for v in row])
    return out


def build(sp, sid):
    maps = {name: {src: nearest(sp.pal, c) for src, c in zip(HIDE, ramp)} for name, ramp in RAMPS.items()}
    rec = sp.record(sid)
    g = sp.groups(rec)
    counts = sp.frame_counts(g)
    header = bytearray(sp.rom[rec - S.ROM_BASE:rec - S.ROM_BASE + 0x4C])
    groups, done = [], {}
    for grp in g:
        if not any(grp):
            groups.append(None)
            continue
        dirs = []
        for arr in grp:
            frames = []
            if arr:
                for fi in range(counts[arr]):
                    xo, yo, w, h, attr, blob = sp.descriptor(arr, fi)
                    if blob not in done:
                        _, _, px = sp.frame_pixels(arr, fi)
                        done[blob] = recolour(px, maps)
                    frames.append((xo, yo, w, h, attr, done[blob]))
            dirs.append(frames)
        groups.append(dirs)
    assert header[2] == len(groups)
    return header, groups, len(done)


def preview(path, sp, groups):
    from PIL import Image
    im = Image.new("RGB", (4 * 66, 3 * 66), (40, 40, 60))   # one body's first three groups
    for r, gi in enumerate((0, 1, 2)):
        for d, frames in enumerate(groups[gi]):
            if not frames:
                continue
            _, _, w, h, _, px = frames[0]
            for y in range(h):
                for x in range(w):
                    if px[y][x]:
                        im.putpixel((d * 66 + x, r * 66 + y), sp.pal[px[y][x]])
    im.save(path)


def main():
    rom = open(sys.argv[1], "rb").read()
    out_c = sys.argv[2]
    pdir = sys.argv[sys.argv.index("--preview-dir") + 1] if "--preview-dir" in sys.argv else None
    sp = S.Sprites(rom)
    w = CWriter()
    w.lines[0] = "/* generated by tools/dinosprites.py from the ROM: King Triceratops and a triceratops recoloured pink, orange and green (the mother dinosaur, her babies)."
    w.lines[1] = " * Build output only; never commit. */"
    report = []
    for sid, prefix in RECORDS:
        header, groups, n = build(sp, sid)
        w.record(prefix, header, groups)
        report.append(f"{prefix}_record {n} frames")
        if pdir:
            os.makedirs(pdir, exist_ok=True)
            preview(os.path.join(pdir, prefix + "_preview.png"), sp, groups)
    w.save(out_c)
    print(f"wrote {out_c}: {', '.join(report)}, {w.bytes} bytes of frames")


if __name__ == "__main__":
    main()
