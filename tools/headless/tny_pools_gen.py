r"""Write tools/headless/tny_pools.txt: each tournament tier's own pool (docs/tournament.md 4d), as two players reach it by pad presses on the story's flags.
usage: python tools/headless/tny_pools_gen.py     (the script is committed; rerun this after changing it here)
Each tier, three draws: the bracket's seats hold the tier's tops and nobody from outside its pool; then a real first fight (no test command deciding it) with both players
mashing, for a crash: the giants and the fighters on their own spawn paths (Super 13) come up here. Fighter ids: tourney.h; seats at eng + 0x6C + SEATS."""
import os

ENG_BR = 0x0203EC6C
SEATS = 4                # TBracket.seat (tourney.h)
L = ["# GENERATED by tools/headless/tny_pools_gen.py", "p2 0"]
ROOKIE_ONLY = "0a 0c"    # Chi-Chi, Chiaotzu
# the tier's flags, its tops, ids that must not be drawn
TIERS = [
    ("Rookie", [], ["04", "02"], ["1b", "1c", "23", "0d", "14"]),
    ("Adept", [85], ["0d"], ["0a", "0c", "1b", "1c", "23"]),
    ("Z-Fighter", [85, 127, 136], ["12"], ["0a", "0c", "1b", "1c", "23"]),
    ("Champion", [85, 127, 136, 146, 191], ["15"], ["00", "0a", "0c", "1b", "1c", "23"]),
    ("Legend", [85, 127, 136, 146, 191, 301, 402, 421, 382], ["23", "1c", "1b"], ["00", "01", "02", "04", "0a", "0c", "0d", "0e"]),
]


def out(*a):
    L.extend(a)


def cmd(n, a=0, b=0):
    out(f"poke32 0x0203FD0C {a:#x}", f"poke32 0x0203FD54 {b:#x}", f"poke32 0x0203FD08 {n}", "frames 10")


def p1(mask):
    out(f"key {mask:#x} 6", "frames 80")


def p2(mask):
    out(f"p2 {mask:#x}", "frames 4", "p2 0", "frames 80")


for ti, (name, flags, tops, never) in enumerate(TIERS):
    for seed in (3, 19, 77):
        out(f"echo === {name} 1 v 1, draw {seed}", "load menu.ss", "p2 0", "maptest 13", "frames 300")
        cmd(23, 0)
        cmd(21, seed)
        if flags:
            out("flags " + " ".join(f"+{f}" for f in flags), "frames 4")
        cmd(5, 15 | 15 << 8, 168 | 306 << 16)
        out("frames 190", "key 0x80 6", "key 1 10", "frames 60", "key 1 6", "frames 60", "key 1 6", "frames 80")
        for _ in range(ti):
            out("key 0x80 6", "frames 20")
        p1(1)
        p1(1)                # 1 v 1
        p1(1)                # 8 fighters
        p1(1)
        p2(1)
        if ti:
            p2(1)
        out("frames 100", f"shot pool{ti}_{seed}")
        need = "".join(rf"(?=.*\b{t}\b)" for t in tops) + "".join(rf"(?!.*\b{n}\b)" for n in never)
        out(rf"echo EXPECT \w+:{need}", f"peek8 {ENG_BR + SEATS:#x} 8")
        if seed == 19:
            out("frames 300", "stepz 0x0203ECFC 200", "frames 60", "map")
            for _ in range(60):
                out("keys 1", "frames 4", "keys 0", "frames 4", "p2 1", "frames 4", "p2 0", "frames 4")
            out(f"shot pool{ti}_{seed}_fight")
for name, ti, flags in (("Legend", 4, TIERS[4][1]),):
    for seed in (5, 31, 64):
        out(f"echo === {name} 2 v 2, draw {seed}: a real fight", "load menu.ss", "p2 0", "maptest 13", "frames 300")
        cmd(23, 0)
        cmd(21, seed)
        out("flags " + " ".join(f"+{f}" for f in flags), "frames 4")
        cmd(5, 15 | 15 << 8, 168 | 306 << 16)
        out("frames 190", "key 0x80 6", "key 1 10", "frames 60", "key 1 6", "frames 60", "key 1 6", "frames 80")
        for _ in range(ti):
            out("key 0x80 6", "frames 20")
        p1(1)
        out("key 0x80 6", "frames 20")
        p1(1)
        p1(1)                # 8 fighters
        p1(1)
        p2(1)
        out("frames 100", r"echo EXPECT \w+:(?=.*\b23\b)(?=.*\b1c\b)(?=.*\b1b\b)", f"peek8 {ENG_BR + SEATS:#x} 8", "frames 300", "stepz 0x0203ECFC 200", "frames 60", "map")
        for _ in range(60):
            out("keys 1", "frames 4", "keys 0", "frames 4", "p2 1", "frames 4", "p2 0", "frames 4")
        out(f"shot pool2v2_{seed}_fight")
here = os.path.dirname(os.path.abspath(__file__))
open(os.path.join(here, "tny_pools.txt"), "w", newline="\n").write("\n".join(L) + "\n")
print(f"tny_pools.txt: {len(L)} lines")
