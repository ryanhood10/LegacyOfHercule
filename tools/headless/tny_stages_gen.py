r"""The tournament in co-op at each stage of the story, by pad presses, on the real story flags (no forced tiers), and the frame
budget in crowded blast fights (Ryan, 2026-11-02: "starting and selecting tournament menu at different parts of the game ...
multiple enemies firing multiple blasts"). tny_coop.txt forces every tier open with stand-in bodies; here the flags decide what
the menu locks and who is in the pool.
usage: python tools/headless/tny_stages_gen.py     writes tools/headless/tny_stages.txt
       ST_HEADLESS=/root/st_perf python tools/headless/st_expect.py tools/headless/tny_stages.txt build/<dir>/log2-coop.gba build/<dir>/hl/menu.ss --out build/<dir>/hl --cols 6
(/root/st_perf: perf_budget.py builds it.) Each stage: the list's shot, then 1 v 1, 2 v 2 and the Rumble of its highest tier from the
director to the record; each fight's "perf" line: frames, lagged frames, the busiest frame against the budget of 280896 cycles."""
import os

L = []
PHASE, BUSY = "0x0203EC04", "0x0203ECFD"
WINS = "0x0203ED78"


def out(*a):
    L.extend(a)


def cmd(n, a=0, b=0):
    out(f"poke32 0x0203FD0C {a:#x}", f"poke32 0x0203FD54 {b:#x}", f"poke32 0x0203FD08 {n}", "frames 10")


def p1(mask):
    out(f"key {mask:#x} 6", "frames 80")


def p2(mask):
    out(f"p2 {mask:#x}", "frames 4", "p2 0", "frames 80")


def expect(rx, *line):
    out(f"echo EXPECT {rx}", *line)


def to_director():
    cmd(5, 15 | 15 << 8, 168 | 306 << 16)
    out("frames 190", "key 0x80 6", "key 1 10", "frames 60", "key 1 6", "frames 60", "key 1 6", "frames 80")


# the stages: name, the story flags (docs/tournament.md 3, tourney_data.c), the highest tier open
STAGES = [
    ("early, after West City", [], 0),
    ("the Android 19 + 13 fight won", [85], 1),
    ("Gingertown done", [85, 127, 136], 2),
    ("the ten-day wait", [85, 127, 136, 146, 191], 3),
    ("the post-game", [85, 127, 136, 146, 191, 301, 402, 421, 382], 4),
]
DIVS = ["1 v 1", "2 v 2", "Rumble"]
TIERS = ["Rookie", "Adept", "Z-Fighter", "Champion", "Legend"]

out("# GENERATED by tools/headless/tny_stages_gen.py", "p2 0")
for si, (name, flags, top) in enumerate(STAGES):
    for d, dname in enumerate(DIVS):
        out(f"echo === {name}: {TIERS[top]} {dname}", "load menu.ss", "p2 0", "maptest 13", "frames 300")
        cmd(23, 0)
        cmd(21, 42 + si * 3 + d)
        if flags:
            out("flags " + " ".join(f"+{f}" for f in flags), "frames 4")
        cmd(40, 30, 0)
        to_director()
        if d == 0:
            out(f"shot st{si}_list")
        for _ in range(top):
            out("key 0x80 6", "frames 20")
        p1(1)               # the tier: a locked line would buzz and stay
        expect(r"0203ec04: 01", f"peek8 {PHASE}")
        for _ in range(d):
            out("key 0x80 6", "frames 20")
        p1(1)               # the division
        out(f"shot st{si}{d}_next")
        if True:
            p1(1)           # 8 fighters; Quick, when the pool has 15 (else this A lands on player 1's own pick)
        p1(1)
        p2(1)
        if d == 0 and top:
            p2(1)
        out("frames 300", f"shot st{si}{d}_in", "map", "perfstart")
        out(f"stepz {BUSY} 400")
        out(f"perfstop st{si}{d}_{TIERS[top]}_{dname.replace(' ', '')}", "frames 30", f"shot st{si}{d}_back")
        expect("map zone 15 area 15", "map")
        expect("0203ec04: 00 00", f"peek8 {PHASE} 2")
        expect(rf"0203ed78:( \w\w){{{top * 3 + d}}} 0[1-9]", f"peek8 {WINS} 15")

# ---- crowded blast fights (tny_blasts.txt): a Rumble's rounds, the kits fighting, with both players holding B and their ki topped up
stage_lines = L[:]
L[:] = ["# GENERATED by tools/headless/tny_stages_gen.py: the frame budget in crowded blast fights", "p2 0"]
NOFIGHT = "0x0203ECFC"
TOP = ["poke16 0x0203F%03X 150" % (0x10 + 0x1C * i) for i in range(7)]
for tier, tname in ((0, "Rookie"), (2, "ZFighter"), (4, "Legend")):
    out(f"echo === Rumble {tname}", "load menu.ss", "p2 0", "maptest 13", "frames 300")
    cmd(24, 0x1F, 3)
    cmd(21, 42)
    cmd(5, 15 | 15 << 8, 168 | 306 << 16)
    out("frames 190")
    cmd(25, 2 | tier << 8, 0xFFFF)
    out(f"stepz {NOFIGHT} 120", "frames 60", f"shot blast_{tname}_start", "map", f"peek8 {PHASE} 4")
    out(f"perf 300 rumble_{tname}_watching", "keys 2", "p2 2")
    for k in range(4):
        out(*TOP, f"perf 120 rumble_{tname}_firing{k}")
    out(f"shot blast_{tname}_mid", "keys 0", "p2 0", f"peek8 {PHASE} 4", "vram")
# the story's fullest fight on a stock map: every enemy on it awake, both players firing
out("echo === a story map full of enemies", "load menu.ss", "p2 0", "maptest 13", "frames 400", "perf 300 wolves_idle", "keys 2", "p2 2")
for k in range(3):
    out("poke16 0x0203F02C 150", "poke16 0x0203F09C 150", f"perf 120 wolves_firing{k}")
out("shot blast_wolves", "save blast_wolves.ss", "keys 0", "p2 0")
here = os.path.dirname(os.path.abspath(__file__))
open(os.path.join(here, "tny_blasts.txt"), "w", newline="\n").write("\n".join(L) + "\n")
L[:] = stage_lines

open(os.path.join(here, "tny_stages.txt"), "w", newline="\n").write("\n".join(L) + "\n")
print(f"tny_stages.txt: {len(L)} lines")
