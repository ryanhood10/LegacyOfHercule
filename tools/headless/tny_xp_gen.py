r"""Write tools/headless/tny_xp.txt: the EXP of a won tournament (docs/tournament.md "EXP"), one and two players, the game's characters and tournament-only fighters.
usage: python tools/headless/tny_xp_gen.py     (the script is committed; rerun this after changing it here)
Paid when the tournament is over and the players stand in the waiting room. Test command 40 decides the fights; everything else is pad presses. The Map Test party:
every slot's EXP 0x299f5f (level 40), player 1 slot 1, player 2 slot 5; a level there is 607735 EXP. A 2 v 2 has both players on the floor. A level box's press is in the
stepz steps; no press after them, the director stands at the door."""
import os

L = ["# GENERATED by tools/headless/tny_xp_gen.py"]
ENTRY = 0x0203F00C
BUSY = "0x0203ECFD"
BASE = 0x299f5f
LEVEL = 607735
YAMCHA, TIEN = 0, 1


def out(*a):
    L.extend(a)


def cmd(n, a=0, b=0):
    out(f"poke32 0x0203FD0C {a:#x}", f"poke32 0x0203FD54 {b:#x}", f"poke32 0x0203FD08 {n}", "frames 10")


def p1(mask):
    out(f"key {mask:#x} 6", "frames 80")


def p2(mask):
    out(f"p2 {mask:#x}", "frames 4", "p2 0", "frames 80")


def run(name, two, double, pick1, pick2, sixteenths1, sixteenths5):
    """pick: True a tournament-only fighter, from the second tab, False the player's own. sixteenths: what slot 1 and slot 5 end up with, in sixteenths of a level."""
    out(f"echo === {name}", "load menu.ss", "p2 0" if two else "p2 off", "maptest 13", "frames 300")
    cmd(23, 0)
    cmd(23, 1, YAMCHA)
    cmd(23, 1, TIEN)
    cmd(40, 30, 0)
    cmd(21, 42)
    cmd(5, 15 | 15 << 8, 168 | 306 << 16)
    out("frames 190", "key 0x80 6", "key 1 10", "frames 60", "key 1 6", "frames 60", "key 1 6", "frames 80")
    p1(1)                # Rookie
    if double:
        p1(0x80)
    p1(1)                # the division
    if pick1:
        p1(0x100)
    p1(1)
    if two:
        if pick2:
            p2(0x100)
            p2(0x10)
        p2(1)
    out(f"stepz {BUSY} 300", "frames 60", f"stepz {BUSY} 20", "frames 30", f"shot xp{name[0]}_end")
    out("findent P1 0x08025604", r"echo EXPECT \w+: 08025604", "peek P1 1")
    for slot, n in ((1, sixteenths1), (5, sixteenths5)):
        v = BASE + LEVEL * n // 16
        out(rf"echo EXPECT {ENTRY + slot * 0x1C + 0x10:08x}: {v:08x}", f"peek {ENTRY + slot * 0x1C + 0x10:#x} 1")
    out("echo EXPECT map zone 15 area 15", "map", "frames 300", "echo ALIVE")


# a won match 4, a first win 16: the division's rounds, and the hidden challenger's fight on a first win when one is drawn
WIN1V1, WIN2V2 = 32, 28
run("A one player on his own character", False, False, False, False, WIN1V1, 0)
run("B one player on a tournament fighter", False, False, True, False, 0, 0)
run("C two players on the game's characters", True, True, False, False, WIN2V2, WIN2V2)
run("D player 1 a tournament fighter, player 2 his own: all to player 2", True, True, True, False, 0, 2 * WIN2V2)
run("E player 2 a tournament fighter, player 1 his own: all to player 1", True, True, False, True, 2 * WIN2V2, 0)
run("F two tournament fighters: nobody", True, True, True, True, 0, 0)
here = os.path.dirname(os.path.abspath(__file__))
open(os.path.join(here, "tny_xp.txt"), "w", newline="\n").write("\n".join(L) + "\n")
print(f"tny_xp.txt: {len(L)} lines")
