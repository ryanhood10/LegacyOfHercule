r"""Write tools/headless/p2_levelup.txt: a level-up box with every player 1 and player 2 pairing that can reach one (docs/perfect-pass.md 9).
usage: python tools/headless/p2_levelup_gen.py     (the script is committed; rerun this after changing it here)
The box's pose goes on player 1's body; it used to be picked by player 2's slot, and a body without that pose wrote over the heap (player 1's entity:
its vtable is the check; player 2's level goes up, player 1 and his active slot stay). Slots: 0 Gohan, 1 Piccolo, 2 Vegeta, 3 Trunks, 4 Goku, 5 Hercule, 6 Krillin."""
import os

L = ["# GENERATED by tools/headless/p2_levelup_gen.py"]
ENTRY = 0x0203F00C
for p1, p2 in ((5, 2), (5, 0), (5, 1), (5, 3), (5, 4), (5, 6), (6, 2), (6, 4), (1, 2), (2, 5)):
    exp = ENTRY + p2 * 0x1C + 0x10
    L += [f"echo === player 1 slot {p1}, player 2 slot {p2} levels up", "load menu.ss", "p2 0", "maptest 13", "frames 300",
          "poke32 FLAGS+0 0xffffffff", "poke32 FLAGS+4 0xffffffff", "poke32 FLAGS+8 0x3e77",
          f"poke8 0x0203F000 {p1}", f"poke8 0x0203FF84 {p2}", f"poke32 {exp:#x} 3335500",
          "poke32 0x0203FD0C 0xc07", "poke32 0x0203FD54 0x1e00f5", "poke32 0x0203FD08 5", "frames 300", "map",
          f"poke32 0x0203FD54 {p2}", "poke32 0x0203FD0C 2", "poke32 0x0203FD08 47", "frames 46", f"shot lu_{p1}{p2}",
          "key 1 6", "frames 60", "key 1 6", "frames 60", "key 1 6", "frames 120", f"shot lu_{p1}{p2}_after",
          "deref E 0x03001120", "findent P1 0x08025604", r"echo EXPECT \w+: 08025604", "peek P1 1",
          fr"echo EXPECT {exp:08x}: 0032e\w\w\w", f"peek {exp:#x} 1", fr"echo EXPECT 0203f000: {p1:02x}", "peek8 0x0203F000", fr"echo EXPECT 0203ff84: {p2:02x}", "peek8 0x0203FF84"]
here = os.path.dirname(os.path.abspath(__file__))
open(os.path.join(here, "p2_levelup.txt"), "w", newline="\n").write("\n".join(L) + "\n")
print(f"p2_levelup.txt: {len(L)} lines")
