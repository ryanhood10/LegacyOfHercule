r"""Write tools/headless/ch4_staging.txt: Gero's stages, the lab and the road staged for the chapter's lineups (data/story/ch4_piccolo.lscript; Ryan, 2026-11-05: "account for 1 player or 2 player or what the combination of characters could be").
usage: python tools/headless/ch4_staging_gen.py     (the script is committed; rerun this after changing it here)
Selectable here: Piccolo 1, Hercule 5, Krillin 6, in either player's hands, or player 1 alone. Each stage also from the trigger rect's far corners (a walk to the mark must not hang), the second generator with the other's flag set.
Only who is played is in a scene (Ryan, 2026-11-05, docs/howto.md "Stage a scene" rule 2): no actor of Piccolo (103, NPC 73) at all, Hercule's sprite 72 only when a player is Hercule
(entrec counts the player: a played Hercule shows 72), checked as each scene opens and at its fight. The lab: 13 (165) stands from the first line. The road's end: Hercule only when played.
Flags 88, 89, 90 at FLAGS+11 bits 0, 1, 2. 0x03001FDC a scene runs (stepz: A on both pads until it is 0): a scene that hung fails the next expect.
A moved actor missing a sprite group overwrites the heap and only crashes later (sprite 73, Piccolo's NPC, has one group; 103 walks): the runner goes on after a crash, so each block ends on the player's vtable and a sane map line."""
import os

L = ["# GENERATED by tools/headless/ch4_staging_gen.py"]
SCENE = "0x03001FDC"
HERCULE = 5


def out(*a):
    L.extend(a)


def actors(**want):
    out("deref TBL 0x0800959C")
    for k, n in want.items():
        sp = int(k[1:])
        out(f"deref R{sp} TBL+{(sp - 7) * 4:#x}", f"echo EXPECT entrec [0-9a-f]+: {n}$", f"entrec R{sp}")


def absent(p1, p2):
    """Piccolo's actors never; Hercule's sprite only on a player who plays him."""
    actors(s103=int(1 in (p1, p2)), s73=0, s72=int(HERCULE in (p1, p2)))


def begin(tag, p1, p2, flags=0):
    out(f"echo === {tag}", "load menu.ss", "p2 off" if p2 is None else "p2 0", "maptest 13", "frames 300", f"poke8 0x0203F000 {p1}")
    if p2 is not None:
        out(f"poke8 0x0203FF84 {p2}")
    out(f"poke8 FLAGS+11 {flags}", "poke16 0x0203F028 900", "poke16 0x0203F098 900")


def warp(area, x, y, zone=8):
    out(f"poke32 0x0203FD0C {zone | area << 8:#x}", f"poke32 0x0203FD54 {x | y << 16:#x}", "poke32 0x0203FD08 5", "frames 300")


def stage(tag, p1, p2, area, x, y, flags=0, shots=0):
    begin(tag, p1, p2, flags)
    warp(area, x, y)
    absent(p1, p2)
    for i in range(shots):
        out(f"shot st_{tag}_{i}", "key 1 6", "frames 100")
    out(f"stepz {SCENE} 80", "frames 30", f"shot st_{tag}_fight", "ents")
    absent(p1, 2 if area == 49 and p2 is not None else p2)   # the road in co-op: player 2 plays Vegeta for the fight
    out(f"echo EXPECT {SCENE[2:].lower()}: 00", f"peek8 {SCENE} 1")
    out(f"echo EXPECT map zone 8 area {area} var 1 player [0-9]+,[0-9]+ ", "map")


LINEUPS = (("P", 1, None), ("H", 5, None), ("K", 6, None), ("PH", 1, 5), ("HP", 5, 1), ("PK", 1, 6), ("HK", 5, 6))
for name, p1, p2 in LINEUPS:
    show = 6 if name in ("P", "H", "PH") else 0
    stage(f"{name}_a13", p1, p2, 13, 192, 278, shots=show)
    stage(f"{name}_a27", p1, p2, 27, 500, 190, shots=show + 3 if show else 0)
    stage(f"{name}_a40", p1, p2, 40, 12, 300, shots=show + 3 if show else 0)
    stage(f"{name}_r49", p1, p2, 49, 200, 700)
for name, p1, p2 in (("H", 5, None), ("PH", 1, 5), ("P", 1, None)):
    stage(f"{name}_a27b", p1, p2, 27, 500, 190, flags=1, shots=4)
    stage(f"{name}_a40b", p1, p2, 40, 12, 300, flags=2)
for name, area, x, y in (("c13a", 13, 115, 278), ("c13b", 13, 270, 278), ("c27a", 27, 500, 154), ("c27b", 27, 500, 231), ("c40a", 40, 12, 243), ("c40b", 40, 12, 366)):
    stage(name, 5, None, area, x, y)

# the lab cutaway (area 46 -> 8/60): 13 beside Gero from the first line, in view; back to area 46 with flag 124
begin("lab", 1, None)
warp(46, 192, 850, 8)
out("frames 200")
actors(s165=1)
for i in range(10):
    out(f"shot st_lab_{i}", "key 1 6", "frames 140")
out(f"stepz {SCENE} 150", "frames 60", "echo EXPECT map zone 8 area 46 ", "map", "ents")
actors(s165=0)

# the lab door (area 46's item 0, Ryan 2026-11-06: the one death): walk up after the cutaway (flag 124 = FLAGS+15 bit 4);
# 13 stands at Gero's side in the lab, swears revenge after 17's blast and flies off, then the stock scene to area 47
# (the cutscene pass, 2026-11-06: the same beats with weight; shots 31-41 are Gero's fall, 13's blasts landing and his take-off)
for name, p1, p2 in (("P", 1, None), ("PH", 1, 5)):
    begin(f"door_{name}", p1, p2)
    out("poke8 FLAGS+15 0x10")
    warp(46, 190, 600)
    walk = "keys 0x40\n" + ("p2 0x40\n" if p2 is not None else "") + "frames 40\nkeys 0\n" + ("p2 0\n" if p2 is not None else "") + "frames 20"
    for _ in range(10):
        out(*walk.split("\n"))
    out("frames 300")
    for i in range(44):                      # through 17's blast (Gero thrown, lying, gone: no 14 after it), 13's revenge, his blasts landing, to his take-off
        out("key 1 6", "frames 90")
        if i in (10, 24, 31, 32, 39, 40, 41):
            out(f"shot st_door_{name}_{i}", "ents")
        if i == 34:
            actors(s14=0, s165=1, s9=1, s11=1)
    out(f"stepz {SCENE} 250", "frames 200", "echo EXPECT map zone 8 area 47 ", "map", "ents")
    actors(s165=0)

# the road's end (18 beaten): after "Who's next?" the fight the stock hid in a black fade (the cutscene pass, 2026-11-06): Vegeta (player 2's
# body, or alone his gold actor 140), Trunks (128) and Gohan (53), Piccolo (player 1's body or his actor 103) and Tien (121) fall in turn; a
# white cut; then the stock ending: exactly one 17 (the fight's twin is reused), no actor left, the first flag words as the stock leaves them.
# Hercule backs Krillin only when someone plays him; alone as Piccolo or Krillin no 72 at all.
for name, p1, p2 in (("P", 1, None), ("K", 6, None), ("H", 5, None), ("PH", 1, 5), ("HP", 5, 1), ("KH", 6, 5)):
    begin(f"{name}_end", p1, p2)
    warp(49, 200, 700)
    out(f"stepz {SCENE} 80", "frames 60", "poke32 0x0203FD08 7", "frames 400", "mash 4 100", "frames 150")
    actors(s140=int(p2 is None), s11=1, s9=1, s8=1)
    out(f"shot st_{name}_end_m0", "frames 200")
    actors(s128=1, s53=1)
    out(f"shot st_{name}_end_m1", "frames 200", f"shot st_{name}_end_m2", "frames 130")
    actors(s121=1, s103=1)
    out(f"shot st_{name}_end_m3", "frames 200", f"shot st_{name}_end_m4", "ents")
    after2 = None if p2 is None else (1 if p1 == HERCULE else HERCULE)      # player 2 after the rebinding
    actors(s9=1, s11=1, s8=1, s76=1, s140=0, s128=0, s53=0, s121=0, s103=int(1 in (p1, after2)))
    if p2 is not None:
        out(f"echo EXPECT 0203ff84: 0{after2}", "peek8 0x0203FF84 1")
    for i in range(40):             # (batch 1, 4.7) on into the aftermath: the kiss, Vegeta's power under his scream, Piccolo's "ALONE"
        out(f"key 1 6", "frames 160")
        actors(s72=int(HERCULE in (p1, after2)))
        out(f"shot st_{name}_end_{i}")
    out(f"stepz {SCENE} 200", "frames 200", "echo EXPECT map zone 6 area 99 ", "map", "ents")
out("echo ALIVE")
here = os.path.dirname(os.path.abspath(__file__))
open(os.path.join(here, "ch4_staging.txt"), "w", newline="\n").write("\n".join(L) + "\n")
print(f"ch4_staging.txt: {len(L)} lines")
