cmd(25, 1 | 2 << 4 | 4 << 8, 0x23 | 0x1c << 8)
out("frames 200")
expect(r"0203ec6c: 08 02", f"peek8 {BR:#x} 2")
expect(r"0203ec0b: 00", f"peek8 {FULL}")

