r"""Write tools/headless/tny_n32.txt: a 2 v 2 of 16 teams, 32 fighters (docs/tournament.md 2b, 26; docs/testing.md "Tournament of 32").
usage: python tools/headless/tny_n32_gen.py     (the script is committed; rerun this after changing it here)
The screen through the ui's stand-in (test command 29), filmed; the menu's locks, the draw and whole tournaments through the real flow by pad presses on the story's flags, test command 40 deciding
all but the real fights. eng 0x0203EC00: phase +4, division +8, tier +9, full +0xB, out +0x13, koed +0x15, opponents in the fight +0x18, the bracket +0x6C (size, rounds, round, match; seats +4, 32 of them;
winner[4][8] +0x24; p1_seat +0x44), the record's wins +0x178 (tier * 3 + division), full_wins +0x187. Fighter ids: tourney.h."""
import os

L = ["# GENERATED by tools/headless/tny_n32_gen.py", "p2 0"]
PHASE, FULL, OUT, KOED, NOPP = "0x0203EC04", "0x0203EC0B", "0x0203EC13", "0x0203EC15", "0x0203EC18"
BR = 0x0203EC6C
SEATS = BR + 4
WINNERS = BR + 0x24
BUSY = "0x0203ECFD"
NOFIGHT = "0x0203ECFC"
WINS_L2 = 0x0203ED78 + 4 * 3 + 1      # wins[Legend, 2 v 2]
FULL_L = 0x0203ED87 + 4               # full_wins[Legend]
CHAMPION = [85, 127, 136, 146, 191, 301, 402, 421]
LEGEND = CHAMPION + [382]
LEGEND_BARE = [85, 127, 136, 146, 191, 421, 382]    # no Cooler, no Broly: the fewest a Legend can have
# the Legend tier's own draw with everything open (16 is the players'): tourney.h ids
OWN = ["0f", "10", "11", "12", "14", "15", "17", "19", "1b", "1c", "1d", "1e", "1f", "20", "21", "22", "23"]
# then from below, strongest first: Namekian, Cell Jr, Paragus, 19, Gero, Mecha Frieza, Frieza, King Cold, Tien, Spopovich, Roshi, Yamu, Tao
BELOW = ["18", "16", "1a", "0d", "0e", "03", "02", "04", "01", "08", "06", "09", "07"]
NEVER = ["00", "05", "0a", "0b", "0c", "13"]        # Yamcha, Videl, Chi-Chi, Chiaotzu (the weakest stay out); Hercule and 16 are the party's
P1SLOT, P2SLOT = 1, 5     # the picks' slots in this script (peeked below at eng + 0xE)
FULL_BRACKET = r"\w+: (?!.*\bff\b)(?!.*\b(\w\w)\b.*\b\1\b)"   # every seat taken, nobody twice


def out(*a):
    L.extend(a)


def cmd(n, a=0, b=0):
    out(f"poke32 0x0203FD0C {a:#x}", f"poke32 0x0203FD54 {b:#x}", f"poke32 0x0203FD08 {n}", "frames 10")


def ui(n, a, b):
    out(f"poke32 0x0203FD0C {a:#x}", f"poke32 0x0203FD54 {b:#x}", f"poke32 0x0203FD08 {n}", "frames 20")


def expect(regex, *line):
    out(f"echo EXPECT {regex}", *line)


def p1(mask):
    out(f"key {mask:#x} 6", "frames 80")


def p2(mask):
    out(f"p2 {mask:#x}", "frames 4", "p2 0", "frames 80")


def to_size_menu(tier, flags, seed, tag, decide=None, unlock=()):
    """To "How many fighters?" of a 2 v 2 by pad presses: the tier, the division."""
    out("load menu.ss", "p2 0", "maptest 13", "frames 300")
    cmd(23, 0)
    for u in unlock:
        cmd(23, 1, u)
    if decide is not None:
        cmd(40, decide[0], decide[1])
    cmd(21, seed)
    out("flags " + " ".join(f"+{f}" for f in flags), "frames 4")
    cmd(5, 15 | 15 << 8, 168 | 306 << 16)
    out("frames 190", "key 0x80 6", "key 1 10", "frames 60", "key 1 6", "frames 60", "key 1 6", "frames 80")
    for _ in range(tier):
        out("key 0x80 6", "frames 20")
    p1(1)
    out("key 0x80 6", "frames 20")      # 2 v 2
    p1(1)
    out(f"shot {tag}_menu")


def down(n):
    for _ in range(n):
        out("key 0x80 6", "frames 20")


def picks():
    p1(1)
    p2(1)


def locked_32(tag):
    """The cursor on 32, its footer, A refused: still the menu (a press more backs out with B)."""
    down(2)
    out(f"shot {tag}_on32")
    p1(1)
    out(f"shot {tag}_refused")
    expect(r"\w+: 01 00 00 00 01", f"peek8 {PHASE} 5")   # the director's, the division chosen, nothing started
    p1(2)
    out(f"shot {tag}_back")


def waiting_room():
    expect("map zone 15 area 15", "map")
    expect(r"0203ec04: 00", f"peek8 {PHASE} 1")


# ---- the screen, on the ui's stand-in ----------------------------------------------------------------------------------------
out("# ---- the screen, on the ui's stand-in: the blocks, the slides, the results, the final four")
out("find UI 0x7A1C0002", "load menu.ss", "p2 0", "maptest 149", "frames 300")
ui(29, 0, 0)
out("find UI 0x7A1C0002")
out("echo === the first look: blocks A to D, then the next match")
ui(29, 3, 32 | 1 << 9)
ui(28, 4, 0)
out("frames 40", "shot f01_block_a", "frames 36", "shot f02_slide_out", "frames 24", "shot f03_slide_in", "frames 30", "shot f04_block_b", "frames 90", "shot f05_block_c", "frames 100", "shot f06_block_d")
out("waitnz UI+0x88 900", "shot f07_vs")
expect(r"0203[0-9a-f]{4}: 00 02", "peek8 UI+141 2")       # the teams' first seats: seat 0's team against the next team
out("key 1 4", "frames 100")
expect(r"0203[0-9a-f]{4}: ([0-9a-f]{4}) \1", "peek16 UI+0x7C 2")   # OBJ VRAM back as it was
out("echo === the first round's results: the players' match, the sweep on block A, a slide, the others")
ui(29, 4, 1)
ui(28, 4, 1)
out("frames 36", "shot f10_loser_grey", "frames 30", "shot f11_winner_walks", "frames 60", "shot f12_sweep", "frames 70", "shot f13_block_b_arrives", "frames 60", "shot f14_block_b_sweep")
out("waitnz UI+0x88 2000", "shot f15_quarterfinal_vs")
expect(r"0203[0-9a-f]{4}: 00 04", "peek8 UI+141 2")
out("key 1 4", "frames 100")
out("echo === the quarterfinals, skipped with A at once")
ui(29, 4, 1)
ui(28, 4, 1)
out("frames 44", "key 1 4", "shot f16_skip_now", "frames 6", "shot f17_skip_after")
out("waitnz UI+0x88 600", "shot f18_semi_vs")
expect(r"0203[0-9a-f]{4}: 00 08", "peek8 UI+141 2")
out("key 1 4", "frames 100")
out("echo === the semifinals: on the final four's page")
ui(29, 4, 1)
ui(28, 4, 1)
out("frames 40", "shot f19_final_four", "frames 60", "shot f20_semi_winner")
out("waitnz UI+0x88 1500", "shot f21_final_vs")
expect(r"0203[0-9a-f]{4}: 00 10", "peek8 UI+141 2")
out("key 1 4", "frames 100")
out("echo === the final: the champion")
ui(29, 4, 1)
ui(28, 4, 1)
out("waitnz UI+0x88 1500", "shot f22_champion", "key 1 4", "frames 100")
expect(r"0203[0-9a-f]{4}: ([0-9a-f]{4}) \1", "peek16 UI+0x7C 2")
expect(r"0203[0-9a-f]{4}: 0000", "peek16 UI+0x80 1")      # no allocation failures
expect(r"04000008: 1c81 1d81 1e83 1f83", "peek16 0x04000008 4")
out("echo === the players out in the first round: the road goes, the rest to the champion, no page out of its order")
ui(29, 0, 0)
ui(29, 3, 32 | 1 << 9)
ui(28, 4, 0)
out("key 1 4", "frames 10", "key 1 4", "waitnz UI+0x88 500", "key 1 4", "frames 100")
ui(29, 4, 0)
ui(29, 4, 0)
ui(29, 4, 0)
ui(29, 4, 0)
ui(28, 4, 1)
out("frames 120", "shot f30_players_out", "frames 200", "shot f31_rest")
out("waitnz UI+0x88 4000", "shot f32_rest_champion", "key 1 4", "frames 100")
expect(r"0203[0-9a-f]{4}: ([0-9a-f]{4}) \1", "peek16 UI+0x7C 2")
ui(29, 0, 0)

# ---- the menu's locks -----------------------------------------------------------------------------------------------------------
out("echo === Rookie 2 v 2: 16 and 32 locked")
to_size_menu(0, [], 42, "m0")
locked_32("m0")
out("echo === Z-Fighter 2 v 2: 16 open, 32 locked (the road and the island done: 20 at most)")
to_size_menu(2, [85, 127, 136, 146], 42, "m2")
locked_32("m2")
out("echo === Champion 2 v 2, everything of the story open: 16 open, 32 locked (26 at most)")
to_size_menu(3, CHAMPION, 42, "m3")
locked_32("m3")
out("echo === Legend, no Cooler, no Broly, somebody beaten who could be picked: 29 left for sure: 32 locked")
to_size_menu(4, LEGEND_BARE, 42, "m4b", unlock=[0])
locked_32("m4b")
out("echo === Legend, no Cooler, no Broly, nobody pickable from the pool: exactly 30: 32 open, every seat taken")
to_size_menu(4, LEGEND_BARE, 7, "m4c", decide=(30, 0))
down(2)
out("shot m4c_on32")
p1(1)
picks()
out("frames 60")
expect(r"0203ec0b: 02", f"peek8 {FULL}")
expect(r"0203ec6c: 20 04", f"peek8 {BR:#x} 2")
expect(FULL_BRACKET, f"peek8 {SEATS:#x} 32")
out(f"stepz {BUSY} 400", "frames 30")
waiting_room()
out("echo === 1 v 1, every tier: the menu is as it was, no 32: down twice wraps to 8 fighters")
out("load menu.ss", "p2 0", "maptest 13", "frames 300")
cmd(23, 0)
out("flags " + " ".join(f"+{f}" for f in LEGEND), "frames 4")
cmd(5, 15 | 15 << 8, 168 | 306 << 16)
out("frames 190", "key 0x80 6", "key 1 10", "frames 60", "key 1 6", "frames 60", "key 1 6", "frames 80")
down(4)
p1(1)
p1(1)
out("shot m1v1_menu")
down(2)
p1(1)
picks()
out("frames 60")
expect(r"0203ec0b: 00", f"peek8 {FULL}")
expect(r"0203ec6c: 08 03", f"peek8 {BR:#x} 2")

# ---- the draw ---------------------------------------------------------------------------------------------------------------------
need = "".join(rf"(?=.*\b{t}\b)" for t in OWN + BELOW) + "".join(rf"(?!.*\b{n}\b)" for n in NEVER)
for seed in (3, 19, 77):
    out(f"echo === Legend 2 v 2, 32 fighters, draw {seed}: the division's all in, then the strongest from below, nobody twice")
    to_size_menu(4, LEGEND, seed, f"d{seed}", decide=(30, 0))
    down(2)
    p1(1)
    picks()
    out("frames 60")
    expect(r"0203ec6c: 20 04 00", f"peek8 {BR:#x} 3")
    expect(FULL_BRACKET, f"peek8 {SEATS:#x} 32")
    expect(rf"\w+:{need}", f"peek8 {SEATS:#x} 32")
    # the players are one team: their seats 2k, 2k + 1 hold their picks
    out(f"peek8 {BR + 0x44:#x} 2", "peek8 0x0203EC0C 2")
    out(f"stepz {BUSY} 500", "frames 30")
    waiting_room()
    expect(r"\w+: 01", f"peek8 {WINS_L2:#x} 1")

out("echo === Picks from the pool: never drawn as well; every seat still taken (test command 25: the picks by id, unlocked first)")
for seed, a, b in ((29, 0x23, 0x04), (31, 0x19, 0x1c)):
    out("load menu.ss", "p2 0", "maptest 13", "frames 300")
    cmd(23, 0)
    cmd(23, 1, a)
    cmd(23, 1, b)
    cmd(40, 30, 0)
    cmd(21, seed)
    out("flags " + " ".join(f"+{f}" for f in LEGEND), "frames 4")
    cmd(5, 15 | 15 << 8, 168 | 306 << 16)
    out("frames 190")
    cmd(25, 1 | 2 << 4 | 4 << 8, a | b << 8)
    out("frames 200")
    expect(rf"0203ec0c: {a:02x} {b:02x}", "peek8 0x0203EC0C 2")
    expect(r"0203ec6c: 20 04", f"peek8 {BR:#x} 2")
    expect(FULL_BRACKET, f"peek8 {SEATS:#x} 32")
    out(f"stepz {BUSY} 500", "frames 30")
    waiting_room()
out("echo === The fewest a Legend can have and two picks out of them (the menu would not offer it; the command can): no 32; its own 15 less two do not fill 16 either: 8, no empty seat")
out("load menu.ss", "p2 0", "maptest 13", "frames 300")
cmd(23, 0)
cmd(23, 1, 0x23)
cmd(23, 1, 0x1c)
