r"""Write tools/headless/cell_staging.txt: the Cell saga's scenes staged for every lineup (data/story/ch7_cell.lscript, tools/gen_cell_games.py;
Ryan, 2026-11-05: "account for 1p mode or 2p mode and a combination of different characters", "just dont add bugs"). docs/testing.md "Cell saga staging".
usage: python tools/headless/cell_staging_gen.py                write the script (committed; rerun this after changing it here)
       python tools/headless/st_expect.py tools/headless/cell_staging.txt ROM menu.ss --out DIR --cols 6 > LOG
       python tools/headless/cell_staging_gen.py check LOG       every vtable in the `ents` lists sane (a sprite without the group an animation needs
                                                                  corrupts the heap and the runner keeps going: a clean CRASH grep is not enough)
Lineups. Zone 12: Vegeta alone, Trunks alone (the fade makes him Vegeta), Vegeta + Trunks, Trunks + Vegeta. The chamber exit clears everyone else's selectable bit, so
Hercule cannot be player 2 there. The Games: alone (Hercule only where the plot needs him: called out after fight 2, 16's head, the
beam struggle and its end; no Hercule on the map at the start of fights 3, J1, 7 and 8), and player 2 chosen as Hercule, Krillin or Vegeta before the ring (player 1 must be Goku for the barrier): player 2's choice
must not change a scene, since his entity is gone in all of them and he is Hercule in the team fights. Each scene is pressed through until 0x03001FDC (a scene runs) clears:
a walk or an animation that hung would leave the next EXPECT failing."""
import os
import re
import sys

SC = "0x03001FDC"
L = ["# GENERATED by tools/headless/cell_staging_gen.py"]


def out(*a):
    L.extend(a)


def expect(rx, *line):
    out(f"echo EXPECT {rx}", *line)


def scene_done(tag):
    # twice: an EXP level-up's box clears the flag for a moment between two scripts of one scene
    out(f"stepz {SC} 150", "frames 120", f"stepz {SC} 150", "frames 120", f"shot cs_{tag}", "ents")
    expect("03001fdc: 00000000", f"peek {SC} 1")


def p2_stands(coop):
    """Is player 2's entity (coop.p2) on the field: in a team fight with two players, nowhere alone."""
    expect("0203ff08: 02" if coop else "0203ff08: 00000000", "peek 0x0203FF08 1")


def presses(tag, n, f=70):
    for i in range(n):
        out(f"shot cs_{tag}_{i:02d}", "key 1 6", f"frames {f}")


def zone12(tag, p1, p2, shots):
    coop = p2 is not None
    out(f"echo === {tag}", "load menu.ss", "p2 0" if coop else "p2 off", "preset +144", "maptest 7", "frames 100", f"poke8 0x0203F000 {p1}")
    if coop:
        out(f"poke8 0x0203FF84 {p2}")
    # the real way in: A on the pad of area 15 (the flight, the warp, the landing)
    out("poke32 0x0203FD0C 0x0F0C", f"poke32 0x0203FD54 {344 | 100 << 16:#x}", "poke32 0x0203FD08 5", "frames 300", "key 1 6", "frames 600")
    expect("0203f000: 02", "peek8 0x0203F000 1")     # Vegeta player 1 behind the fade
    if coop:
        expect("0203ff84: 03", "peek8 0x0203FF84 1")
    if shots:
        presses(f"{tag}_a", 2)
        out("mash 12 70")
        presses(f"{tag}_b", 8)
    scene_done(f"{tag}_semi")
    expect("map zone 12 area 4", "map")
    out("poke32 0x0203FD08 7", "frames 120")
    if shots:
        out("mash 22 70")
        presses(f"{tag}_c", 8)
    out("mashmap 12 6 150")
    if shots:
        out("frames 700")
        out("mash 5 70")
        presses(f"{tag}_d", 16)
    scene_done(f"{tag}_perfect")
    expect("0203f000: 03", "peek8 0x0203F000 1")     # Trunks player 1
    if coop:
        expect("0203ff84: 06", "peek8 0x0203FF84 1")  # Krillin player 2 on Vegeta's pad
    p2_stands(coop)
    out("poke32 0x0203FD08 7", "frames 120")
    scene_done(f"{tag}_stage2")
    out("poke32 0x0203FD08 7", "frames 120")
    if shots:
        presses(f"{tag}_e", 6, 40)
        out("frames 60")
        presses(f"{tag}_f", 8, 60)
    scene_done(f"{tag}_end")
    expect("map zone 12 area 6", "map")
    expect("[0-9a-f]+: [89a-f][0-9a-f]", "peek8 FLAGS+18 1")   # flag 151, Perfect Cell's end
    expect("0203f000: 03", "peek8 0x0203F000 1")
    if coop:
        expect("0203ff84: 06", "peek8 0x0203FF84 1")
    p2_stands(coop)


def herc(n):
    """Hercule's sprite 72 on the map: alone he is in no scene before a fight (Ryan, 2026-11-05), with two players player 2's entity is him in a team fight."""
    out("deref TBL 0x0800959C", f"deref R72 TBL+{(72 - 7) * 4:#x}")
    expect(f"entrec [0-9a-f]+: {n}$", "entrec R72")


def win(stat, who):
    out("poke32 0x0203F9B0 0xCE11CA3E", f"poke8 0x0203F9B5 {stat}", "poke8 0x0203F9B6 0", "stepz 0x0203F9B5 150")
    expect(f"0203f9b7: {who}", "peek8 0x0203F9B7 1")


def games(tag, p2):
    coop = p2 is not None
    duo = "80" if coop else "00"
    out(f"echo === {tag}", "load menu.ss", "p2 0" if coop else "p2 off", "preset +191 +421", "maptest 323", "frames 200", "poke8 0x0203F000 4")
    if coop:
        out(f"poke8 0x0203FF84 {p2}")
    out("poke32 0x0203FD0C 0x010E", "poke32 0x0203FD54 0x00700108", "poke32 0x0203FD08 5", "frames 200", "key 0x40 20", "key 1 6", "frames 120")
    if coop:
        out("p2 0x40")
    out("key 0x40 160")
    if coop:
        out("p2 0")
    out("waitmap 14 2 300", "frames 60")
    scene_done(f"{tag}_ring")
    win(22, "14")
    scene_done(f"{tag}_desert")
    # fight 2's end places the two (docs/cutscenes/batch3 0, 3.3): the fight ends away from where the scene's pans look
    out("deref P1 0x03001FA8", f"poke32 P1+0x158 {250 << 8:#x}", f"poke32 P1+0x15C {330 << 8:#x}", "frames 4")
    win(23, "24")
    out("frames 200", f"shot cs_{tag}_giveup")
    expect("map zone 14 area 3 var [0-9]+ player 368,440", "map")
    scene_done(f"{tag}_f3")      # fight 3: player 2's Hercule beside Gohan, or Gohan alone and no actor
    if coop:
        expect("0203ff84: 05", "peek8 0x0203FF84 1")
    p2_stands(coop)
    herc(1 if coop else 0)
    win(24, duo)
    scene_done(f"{tag}_j1")
    herc(0)
    win(27, "16")
    scene_done(f"{tag}_j2")
    win(27, "21")
    scene_done(f"{tag}_j3")
    win(142, "12")
    scene_done(f"{tag}_j4")
    win(142, "23")
    scene_done(f"{tag}_f7")      # fight 7
    if coop:
        expect("0203ff84: 05", "peek8 0x0203FF84 1")
    p2_stands(coop)
    herc(1 if coop else 0)
    win(25, duo)
    # Android 18 lies where Cell spat her out until the two Cells' fade (she walked off by herself; 3.7): there after the bomb's lines, gone at fight 8
    out("deref TBL 0x0800959C", f"deref R11 TBL+{(11 - 7) * 4:#x}", "mash 14 100", f"shot cs_{tag}_18")
    expect("entrec [0-9a-f]+: 1$", "entrec R11")
    scene_done(f"{tag}_f8")      # fight 8
    expect("entrec [0-9a-f]+: 0$", "entrec R11")
    if coop:
        expect("0203ff84: 05", "peek8 0x0203FF84 1")
    p2_stands(coop)
    herc(1 if coop else 0)
    win(26, duo)
    out("frames 1500", f"shot cs_{tag}_struggle", "mash 42 100", f"shot cs_{tag}_after1", "ents", "mash 14 100", f"shot cs_{tag}_after2", "mash 8 100", f"shot cs_{tag}_after3")
    out("mashmap 6 99 200", "frames 120", f"shot cs_{tag}_world", "ents")
    expect("map zone 6 area 99", "map")
    expect("[0-9a-f]+: 1a", "peek8 0x0203F084 1")   # Goku's halo


if len(sys.argv) > 2 and sys.argv[1] == "check":
    bad = [ln for ln in open(sys.argv[2]) for m in [re.search(r" vt ([0-9a-f]{8}) ", ln)] if m and not re.fullmatch(r"080[0-9a-f]{5}|0203[0-9a-f]{4}", m.group(1))]
    n = sum(" vt " in ln for ln in open(sys.argv[2]))
    print(f"{n} entities listed, {len(bad)} with a garbage vtable")
    print("".join(bad[:10]), end="")
    sys.exit(1 if bad or not n else 0)

zone12("V", 2, None, True)
zone12("T", 3, None, False)
zone12("VT", 2, 3, True)
zone12("TV", 3, 2, False)
games("alone", None)
games("H", 5)
games("K", 6)
games("Ve", 2)
out("echo ALIVE")
here = os.path.dirname(os.path.abspath(__file__))
open(os.path.join(here, "cell_staging.txt"), "w", newline="\n").write("\n".join(L) + "\n")
print(f"cell_staging.txt: {len(L)} lines")
