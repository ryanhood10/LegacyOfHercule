"""Write tools/headless/tny_coop.txt: the tournament in co-op, as two players reach it (docs/perfect-pass.md 11.5).
usage: python tools/headless/tny_coop_gen.py     (the script is committed; rerun this after changing it here)

Every menu and pick is a pad press (player 1's through `key`, player 2's through `p2`); test command 40 decides the fights
(after a few frames of each, a win or the listed losses), everything else is the real flow. Addresses: eng 0x0203EC00
(+4 phase, pending, kind, result, division, tier, players, full; +0xC picks; +0x68 the bracket's...; +0xFC t_nofight, +0xFD
t_busy), the record's wins at eng + 0x178 (tier * 3 + division), paid at eng + 0x19C."""
import os

PHASE, PICKS, BUSY = "0x0203EC04", "0x0203EC0C", "0x0203ECFD"
WINS, PAID = "0x0203ED78", "0x0203ED9C"
L = []


def out(*lines):
    L.extend(lines)


def cmd(n, a=0, b=0):
    out(f"poke32 0x0203FD0C {a:#x}", f"poke32 0x0203FD54 {b:#x}", f"poke32 0x0203FD08 {n}", "frames 10")


def warp(zone, area, x, y):
    out(f"poke32 0x0203FD0C {zone | area << 8:#x}", f"poke32 0x0203FD54 {x | y << 16:#x}", "poke32 0x0203FD08 5", "frames 200")


def p1(mask):
    out(f"key {mask:#x} 6", "frames 80")


def p2(mask):
    out(f"p2 {mask:#x}", "frames 4", "p2 0", "frames 80")


def expect(regex, *line):
    out(f"echo EXPECT {regex}", *line)


def start(seed=42, record=True):
    """Map Test 13 with player 2 in, the record wiped, a known draw."""
    out("p2 0", "maptest 13", "frames 300")
    if record:
        cmd(23, 0)
    cmd(21, seed)


def to_director(rookie=True):
    """In front of the director: Down onto him, A, his two lines. The next press answers the first menu, the tier list
    (every tier, the closed ones locked); rookie: A takes the first line, the next press answers the division."""
    warp(15, 15, 168, 306)
    out("key 0x80 6", "key 1 10", "frames 60", "key 1 6", "frames 60", "key 1 6", "frames 80")
    if rookie:
        p1(1)


def finish(steps=150):
    """A on both pads until the tournament is over and the curtain is open."""
    out(f"stepz {BUSY} {steps}", "frames 30")


def back_in_room():
    expect("map zone 15 area 15", "map")
    expect(r"0203ec04: 00 00", f"peek8 {PHASE} 2")


out("# The tournament in co-op, by pad presses, as two players reach it (docs/perfect-pass.md 11.5, docs/testing.md \"Tournament in",
    "# co-op\"). GENERATED by tools/headless/tny_coop_gen.py. Self-checking (regfull.sh):",
    "#   python tools/headless/st_expect.py tools/headless/tny_coop.txt build/<dir>/log2-coop.gba build/<dir>/hl/menu.ss --out build/<dir>/hl --cols 6",
    "# Ryan's report: 2 v 2 and the Rumble, both picks made, \"it just dropped back to the waiting room\". Before the fix",
    "# block 1 fails there: player 2's pad's A (the GBA's B under tools/p2_keys.py's default) backed out of the whole tournament.")

out("echo === 1. An early save's party (Gohan and Krillin only, one tier): 2 v 2, player 2 picks with B (his pad's A)")
start()
for slot in range(9):
    if slot not in (0, 6):
        out(f"poke32 {0x0203F00C + slot * 0x1C + 0x14:#x} 0")
out("poke8 0x0203F000 6", "poke8 0x0203FF84 0", "frames 10")
cmd(40, 30, 0)
to_director()
out("shot c1_division")
p1(0x80)
p1(1)
p1(1)               # 8 fighters
out("shot c1_p1_select")
expect(r"0203ec04: 01 00 00 00 01 00 02", f"peek8 {PHASE} 7")
p1(1)
out("shot c1_p2_select")
expect(r"0203ec0c: 33 ff", f"peek8 {PICKS} 2")
p2(2)   # GBA B
out("frames 30")
expect(r"0203ec0c: 33 32", f"peek8 {PICKS} 2")
out("frames 40", "shot c1_bracket_1", "frames 80", "shot c1_bracket_2")
expect("map zone 15 area 16", "map")
out("find UI 0x7A1C0002")
out("echo --- the bracket's banner names teams: the first seats of two teams, not two partners")
expect(r"\w+: 0[0246] 0[0246]", "peek8 UI+141 2")
finish()
out("shot c1_back")
back_in_room()
out("echo --- the record: Rookie 2 v 2 won once; the first-win capsule paid (bit 1)")
expect(r"0203ed78: 00 01 00", f"peek8 {WINS} 3")
expect(r"0203ed9c: 00000002", f"peek {PAID}")
out("echo --- own characters back: player 1 Krillin (6), player 2 Gohan (0), both HP full")
expect(r"0203f000: 06", "peek8 0x0203F000")
expect(r"0203ff84: 00", "peek8 0x0203FF84")

out("echo === 2. The way back: player 1's B on player 2's screen, on his own, on the list; player 2's B on a list does nothing")
to_director()
p2(2)
expect(r"0203ec04: 01", f"peek8 {PHASE}")
p1(1)        # 1 v 1
p1(1)        # 8 fighters
p1(1)        # player 1's pick
out("shot c2_p2_select")
p1(2)        # player 1's B: back to player 1's screen
out("shot c2_back_p1")
p1(1)
p1(2)
p1(2)        # the size
p1(2)        # and his own B: the list
out("shot c2_back_list")
p2(2)
expect(r"0203ec04: 01", f"peek8 {PHASE}")
p1(2)        # back to the tier list
p1(2)        # and its B leaves
out("frames 60", "shot c2_left")
back_in_room()

out("echo === 3. Both players down in a 2 v 2 (real hits): the match is lost, no game over; player 1 down first, player 2 last")
cmd(40, 0, 0)
cmd(21, 7)
to_director()
p1(0x80)
p1(1)
p1(1)
p1(1)
p2(1)
out("stepz 0x0203ECFC 30", "frames 60")
out("poke32 0x0203FD0C 0", "poke32 0x0203FD08 10", "frames 30", "shot c3_p1_down")
out("poke16 0x0203F00C 1", "shot c3_p2_1hp", "find RV 0x5EB1BE00")
expect(r"\w+: 5eb1be00 0[23]", "peek RV 2")
out("frames 2500", "shot c3_after")
out("echo --- never the game over (the revive's over byte, +0x22)")
expect(r"\w+: 00", "peek8 RV+0x22")
finish()
back_in_room()
expect(r"0203ed78: 00 01 00", f"peek8 {WINS} 3")

out("echo === 3b. Player 1 down, player 2 finishes the fight alone: the result line closes (player 1's pad was cut under it)")
cmd(21, 9)
to_director()
p1(0x80)
p1(1)
p1(1)
p1(1)
p2(1)
out("stepz 0x0203ECFC 30", "frames 30")
out("poke32 0x0203FD0C 0", "poke32 0x0203FD08 10", "frames 30", "shot c3b_p1_down")
cmd(40, 20, 0)
finish()
back_in_room()
expect(r"0203ed78: 00 02 00", f"peek8 {WINS} 3")

out("echo === 4. The Rumble with player 2 in, every round, the trophy, the prize; 1 v 1: turns, a lost match, the duel final")
cmd(40, 30, 0)
cmd(21, 42)
to_director()
p1(0x80)
p1(0x80)
p1(1)
p1(1)
p1(1)
p2(1)
out("frames 200", "shot c4_rumble")
expect("map zone 15 area 16", "map")
finish(200)
back_in_room()
expect(r"0203ed78: 00 02 01", f"peek8 {WINS} 3")
expect(r"0203ed9c: 00000006", f"peek {PAID}")
# a co-op 1 v 1: player 1 loses his first match (fight 0), player 2 plays on through the bracket alone
cmd(40, 30, 1)
cmd(21, 42)
to_director()
p1(1)
p1(1)
p1(1)
p2(1)
out("frames 200", "shot c4_1v1_lost")
finish(200)
back_in_room()
out("echo --- the record's unchanged or won by player 2: whatever it is, the game is back and the characters are")
expect(r"0203f000: 06", "peek8 0x0203F000")
expect(r"0203ff84: 00", "peek8 0x0203FF84")
# both through to the final: player 2 wins the duel
cmd(40, 30, 2 << 24)
cmd(21, 42)
to_director()
p1(1)
p1(1)
p1(1)
p2(1)
finish(240)
back_in_room()
expect(r"0203ed78: 0[1-9] 02 01", f"peek8 {WINS} 3")

out("echo === 4b. Tournament playables picked on the screens' second tab by both (Yamcha, Tien): carriers, own entries back")
cmd(23, 1, 0)
cmd(23, 1, 1)
cmd(40, 30, 0)
cmd(21, 42)
to_director()
p1(0x80)
p1(1)
p1(1)
p1(0x100)    # R: the Tourney tab
p1(1)
p2(0x100)
p2(0x10)
out("shot c4b_p2")
p2(1)
out("frames 30")
expect(r"0203ec0c: 00 01", f"peek8 {PICKS} 2")
out("frames 200", "shot c4b_ring")
finish(200)
back_in_room()
expect(r"0203f000: 06", "peek8 0x0203F000")
expect(r"0203ff84: 00", "peek8 0x0203FF84")
out("echo --- own bodies: slot 6's and slot 0's display rows, the party flags in")
out("peek 0x0203F0B4 7", "peek 0x0203F00C 7")
out("shot c4b_back")

out("echo === 5. A two-player game over with player 1 down first: \"You have died!\" closes (his pad was cut: the game hung there)")
out("load menu.ss", "p2 0", "maptest 7", "frames 300")
out("poke32 0x0203FD0C 0", "poke32 0x0203FD08 10", "frames 20", "find RV 0x5EB1BE00", "poke16 RV+0xC 5", "frames 700", "shot c5_died")
expect("map zone 1 area 7", "map")
out("key 1 6", "frames 200", "shot c5_closed", "key 1 6", "frames 300", "shot c5_title")
out("echo --- on the way to the title: no player 1 any more (it stayed on the line before the fix)")
expect(r"map zone 1 area 7 var 1 player -1,-1", "map")

out("echo === 6. Every tier and division, the director by pad, player 2 in; the whole party (F9's shape), every tier forced open")
out("load menu.ss")
start(record=True)
cmd(24, 0x1F, 3)
tiers = ["Rookie", "Adept", "Z-Fighter", "Champion", "Legend"]
for t, name in enumerate(tiers):
    for d, dname in enumerate(["1 v 1", "2 v 2", "Rumble"]):
        out(f"echo --- {name} {dname}")
        cmd(40, 30, 0)
        cmd(21, 42 + t * 3 + d)
        to_director(rookie=False)
        for _ in range(t):
            out("key 0x80 6", "frames 20")
        p1(1)               # the tier
        for _ in range(d):
            out("key 0x80 6", "frames 20")
        p1(1)               # the division
        if True:
            p1(1)           # 8 fighters; Quick (the list only when the pool has 15; A then lands on player 1's own pick)
        p1(1)
        p2(1)
        if t and d == 0:
            p2(1)
        out("frames 300", f"shot c6_{t}{d}")
        finish(300)
        back_in_room()
        expect(rf"0203ed78:( \w\w){{{t * 3 + d}}} 0[1-9]", f"peek8 {WINS} 15")

out("echo === 6b. A Full bracket with player 2 in: Champion, the list's second line, 16 seats, the record's Full win")
cmd(40, 30, 0)
cmd(21, 77)
to_director(rookie=False)
for _ in range(3):
    out("key 0x80 6", "frames 20")
p1(1)
p1(1)               # 1 v 1
out("key 0x80 6", "frames 20")
p1(1)               # Full
p1(1)
p2(1)
out("frames 300", "shot c6b_full")
expect(r"0203ec6c: 10 04", "peek8 0x0203EC6C 2")
finish(300)
back_in_room()
out("echo --- full_wins[Champion]")
expect(r"0203ed8a: 01", "peek8 0x0203ED8A")

here = os.path.dirname(os.path.abspath(__file__))
open(os.path.join(here, "tny_coop.txt"), "w", newline="\n").write("\n".join(L) + "\n")
print(f"tny_coop.txt: {len(L)} lines")
