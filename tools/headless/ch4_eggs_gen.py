r"""Write tools/headless/ch4_eggs.txt: the generator's eggs (data/story/ch4_eggs.*, docs/scripts.md), two players and one, by pad presses from the door to the generator's end.
usage: python tools/headless/ch4_eggs_gen.py     (the script is committed; rerun this after changing it here)
No test warp once in the room: a load would spawn what the scene must spawn, and test the items for it; player 1 is moved by his position. Flags: 117-119 at FLAGS+14 bits 5-7, 120-123 at FLAGS+15 bits 0-3,
476, 477, 478 at FLAGS+59 bits 4, 5, 6. Test command 7 wins the mother's half of the fight. 0x03001FDC a scene runs. Her HP each half: 840 with two players, 600 alone; a baby stock 275, 412 with two.
The two-player pass shoots every page of the three scenes (her lines in her speaker box, portrait 173) and the walk-off every 30 frames (eg2p_out*)."""
import os

L = ["# GENERATED by tools/headless/ch4_eggs_gen.py"]
SCENE = "0x03001FDC"
PLAYER = "0x08025604"


def out(*a):
    L.extend(a)


def warp(zone, area, x, y):
    out(f"poke32 0x0203FD0C {zone | area << 8:#x}", f"poke32 0x0203FD54 {x | y << 16:#x}", "poke32 0x0203FD08 5", "frames 300")


def expect(rx, *line):
    out(f"echo EXPECT {rx}", *line)


def to_egg(x):
    """Stand under the egg and face it (the generator stops the walk)."""
    out(f"findent PL {PLAYER}", f"poke32 PL+0x158 {x << 8:#x}", f"poke32 PL+0x15C {318 << 8:#x}", "keys 0x40", "frames 16", "keys 0", "frames 10")


def scene_end(shot=None, then=()):
    out("frames 40")
    if shot:
        out(f"shot {shot}")
    for step in then:      # shots of the boxes before stepz ends the scene
        step()
    out(f"stepz {SCENE} 60", "frames 60")


def full():
    out("poke16 0x0203F028 900", "poke16 0x0203F02A 900", "poke16 0x0203F098 900", "poke16 0x0203F09A 900")


def boxes(*shots):
    """A box is up: A, then (frames, shot) for the next one; her lines show her portrait 173 (two players only)."""
    for n, name in shots:
        out("key 1 6", f"frames {n}", f"shot {name}")


def watch(*shots):
    """No key: (frames, shot) while the scene plays on by itself."""
    for n, name in shots:
        out(f"frames {n}", f"shot {name}")


for tag, two in (("2p", True), ("1p", False)):
    out(f"echo === {tag}: the door north of area 44 leads to the generator", "load menu.ss", "p2 0" if two else "p2 off", "maptest 13", "frames 300")
    warp(8, 44, 224, 40)
    out("keys 0x40", "frames 60", "keys 0", "frames 120")
    expect("map zone 8 area 50", "map")
    out(f"shot eg{tag}_room")
    out(f"echo === {tag}: the mother stands by the generator; the first egg brings the scene and the fight")
    to_egg(284)
    out(f"shot eg{tag}_before", "key 1 6", "frames 50", f"shot eg{tag}_line1")
    if two:
        boxes((60, "eg2p_line1b"), (90, "eg2p_slick"), (60, "eg2p_crack"), (90, "eg2p_line4"), (60, "eg2p_line4b"),
              (200, "eg2p_mother1"), (60, "eg2p_mother1b"), (90, "eg2p_mother2"))
    scene_end()
    out(f"shot eg{tag}_fight", "ents")
    expect(r"0203f116: 40", "peek8 FLAGS+14 1")
    expect(r"0203f143: 10", "peek8 FLAGS+59 1")
    full()
    out("frames 200", f"shot eg{tag}_fight2", "ents")
    out(f"echo === {tag}: another egg does nothing during the fight")
    full()
    to_egg(244)
    out("key 1 6", "frames 40")
    expect(r"0203f116: 40", "peek8 FLAGS+14 1")
    out(f"echo === {tag}: half her health: the eggs left hatch, two babies, she stands again")
    out("poke32 0x0203FD08 7", "frames 60")
    scene_end(f"eg{tag}_hatch_line", [lambda: boxes((60, "eg2p_hatch1b"), (90, "eg2p_hatch2"), (110, "eg2p_rattle"), (90, "eg2p_crack2"),
                                                                    (60, "eg2p_crack2b"), (90, "eg2p_babies"), (60, "eg2p_babiesb"))] if two else ())
    out("frames 30", f"shot eg{tag}_hatched", "ents")
    expect(r"0203f116: e0", "peek8 FLAGS+14 1")
    expect(r"0203f143: 50", "peek8 FLAGS+59 1")
    full()
    out(f"echo === {tag}: she and the babies fight on; an egg's place does nothing")
    out("frames 240", f"shot eg{tag}_three", "ents")
    full()
    to_egg(324)
    out("key 1 6", "frames 40")
    expect(r"0203f143: 50", "peek8 FLAGS+59 1")
    full()
    out(f"echo === {tag}: she falls: her line, the map again without them")
    out("poke32 0x0203FD08 7", "frames 60")
    scene_end(f"eg{tag}_end_line", [lambda: boxes((60, "eg2p_end_lineb"), (30, "eg2p_out0")),   # the warp, then she and the first baby walk off;
                                    lambda: watch(*[(30, f"eg2p_out{k}") for k in range(1, 15)])] if two else ())   # the second waits, runs late
    out("frames 60", f"shot eg{tag}_won", "ents")
    expect(r"0203f143: 70", "peek8 FLAGS+59 1")
    out(f"echo === {tag}: every tube breaks; the third ends the generator")
    for x, bit in ((244, "01"), (284, "03")):
        to_egg(x)
        out("key 1 6", "frames 80")
        expect(rf"0203f117: {bit}", "peek8 FLAGS+15 1")
    to_egg(324)
    out("key 1 6", "frames 60", f"shot eg{tag}_last", "frames 900", f"stepz {SCENE} 60", "frames 200", f"shot eg{tag}_end", "map")
    expect(r"0203f117: 0f", "peek8 FLAGS+15 1")
    out(f"echo ALIVE {tag}")
# a player leaves the room during the second half: she alone on the way back, and her end still opens the tubes
out("echo === leaving the room in the second half", "load menu.ss", "p2 0", "maptest 13", "frames 300")
warp(8, 44, 224, 40)
out("keys 0x40", "frames 60", "keys 0", "frames 120")
to_egg(244)
out("key 1 6", "frames 50")
scene_end()
out("poke32 0x0203FD08 7", "frames 60")
scene_end()
full()
out("frames 60")
warp(8, 44, 224, 40)
full()
warp(8, 50, 288, 340)
out("shot eg_back", "ents")
expect("map zone 8 area 50", "map")
expect(r"0203f143: 50", "peek8 FLAGS+59 1")
out("poke32 0x0203FD08 7", "frames 60")
scene_end()
expect(r"0203f143: 70", "peek8 FLAGS+59 1")
to_egg(244)
out("key 1 6", "frames 80")
expect(r"0203f117: 01", "peek8 FLAGS+15 1")
out("echo ALIVE back")
# a baby can be hurt and dies (stock stat 94 could not be): alone in the room, spawned as the hatching does (test command 1), player 1 beside it
out("echo === a baby alone: punches", "load menu.ss", "p2 0", "maptest 13", "frames 300")
warp(8, 50, 288, 336)
out("poke32 0x0203FD0C 3", "poke32 0x0203FD54 0", "poke32 0x0203FD08 1", "frames 30")
expect("entities 15", "ents")
out("findent B 0x0203FB04", f"findent PL {PLAYER}")
for k in range(6):
    full()
    out("deref BX B+0x158", "deref BY B+0x15C", "poke32 PL+0x158 BX+0x1000", "poke32 PL+0x15C BY", "keys 0x20", "frames 1", "keys 1", "frames 3", "keys 0", "frames 20")
out("frames 60")
expect("entities 14", "ents")
out("echo ALIVE baby")
here = os.path.dirname(os.path.abspath(__file__))
open(os.path.join(here, "ch4_eggs.txt"), "w", newline="\n").write("\n".join(L) + "\n")
print(f"ch4_eggs.txt: {len(L)} lines")
