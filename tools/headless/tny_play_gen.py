"""Writes tools/headless/tny_play.txt, the playables test (docs/testing.md "Tournament playables"): every
tournament playable (display rows 29-79, tools/tnyplayables.py) written into party slot 7 with the kit and the
numbers of src/coop/tny_play.c (pokes: no test command is the playables piece's), played as player 2 and then
as player 1: walk, punch, each of the four abilities (the gate word 0x0300208C set before each), EP peeked
after each ability; screenshots of the walk, the punch and every ability as player 2, the first ability as player
1 (six and three per fighter: the sheet's command line must stay under Windows' limit).  usage: python tools/headless/tny_play_gen.py [--only TF_A,TF_B]"""
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, ".."))
import tnyplayables as T  # noqa: E402

SLOT = 7
E = 0xC + SLOT * 0x1C            # slot 7's entry in the party block
LEAD = dict(hp=400, ep=300, str=12000, pow=12000, end=12000, exp=1000000)   # a level-40-ish lead
AB = dict(BB=0, BURN=1, KI=2, KAME=3, MAS=4, SCAT=8, HPUNCH=14, HKICK=15, MEGA=16, TAUNT=17, RUSH=19, SHOCK=20,
          DISC=21, BURST=23)


def kits():
    src = open(os.path.join(HERE, "..", "..", "src", "coop", "tny_play.c"), encoding="utf-8").read()
    out = {}
    for m in re.finditer(r"\[(TF_\w+)\]\s*=\s*\{\s*\{([^}]*)\},\s*(\d+),\s*(\d+),\s*(\d+),\s*(\d+),\s*(\d+)\s*\}", src):
        ab = [AB[a.strip()] for a in m.group(2).split(",")]
        out[m.group(1)] = (ab, [int(m.group(i)) for i in range(3, 8)])
    return out


def entry(row, ab, p):
    hp, ep = LEAD["hp"] * p[0] // 100, LEAD["ep"] * p[1] // 100
    s, w, e = (LEAD[k] * q // 100 for k, q in zip(("str", "pow", "end"), p[2:]))
    return [f"poke16 PARTY+{E:#x} {hp}", f"poke16 PARTY+{E + 2:#x} {hp}", f"poke16 PARTY+{E + 4:#x} {ep}",
            f"poke16 PARTY+{E + 6:#x} {ep}", f"poke8 PARTY+{E + 8:#x} {row}", f"poke8 PARTY+{E + 9:#x} 0",
            f"poke16 PARTY+{E + 0xA:#x} {s}", f"poke16 PARTY+{E + 0xC:#x} {w}", f"poke16 PARTY+{E + 0xE:#x} {e}",
            f"poke32 PARTY+{E + 0x10:#x} {LEAD['exp']}", f"poke32 PARTY+{E + 0x14:#x} 0x7B",
            f"poke32 PARTY+{E + 0x18:#x} {ab[0] | ab[1] << 8 | ab[2] << 16 | ab[3] << 24:#x}"]


def warp(x=0x1F4):
    return ["poke32 0x0203FD0C 0x0702", f"poke32 0x0203FD54 {0x01AE0000 | x:#x}", "poke32 0x0203FD08 5", "frames 200",
            "poke32 0x0203FD08 13", "frames 20"]


def moves(name, who, ab):
    pad = (lambda m: f"p2 {m}") if who == 2 else (lambda m: f"keys {m}")
    t = name[3:].lower()[:8]
    out = [pad("0x20"), "frames 16", f"shot t{who}{t}0", pad("0x10"), "frames 10", pad(0), "frames 10",
           pad(1), "frames 3", pad(0), "frames 4", pad(1), "frames 3", pad(0), "frames 4", f"shot t{who}{t}1",
           "frames 40"]
    for i in range(4):
        held = 30 if ab[i] == AB["KAME"] else 6      # the Kamehameha fires after 24 frames of B held
        out += ["poke32 0x0300208C 1", f"poke8 PARTY+{E + 9:#x} {i}", pad(2), f"frames {held}"] + (
            [f"shot t{who}{t}{i + 2}"] if who == 2 or i == 0 else []) + [
            "frames 16", pad(0), "frames 50", f"peek16 PARTY+{E + 4:#x} 1"]
    return out


def main():
    only = sys.argv[sys.argv.index("--only") + 1].split(",") if "--only" in sys.argv else None
    rows, k = T.playable_rows(), kits()
    names = [n for n in rows if not only or n in only]
    L = ["# Tournament playables (src/coop/tny_play.c, tools/tnyplayables.py; docs/testing.md \"Tournament playables\").",
         "# Generated by tools/headless/tny_play_gen.py: every TR_BEAT / TR_CHALLENGER fighter's entry (display row,",
         "# kit, numbers at a fixed lead) poked into party slot 7 (PARTY+0xD0), played by player 2 (Map Test zone 2",
         "# area 7, enemies cleared), then by player 1 alone: walk, the A combo, abilities 0-3 (EP after each).",
         "#   python tools/headless/st_test.py tools/headless/tny_play.txt ROM build/<dir>/hl/menu.ss --out build/<dir>/hl --cols 6",
         "p2 0", "maptest 13", "frames 300"] + warp() + ["echo == player 2 on slot 7"]
    first = True
    for n in names:
        row = rows[n][0]
        ab, p = k[n]
        L += [f"echo == P2 {n} row {row} abilities {ab}"] + entry(row, ab, p)
        if first:
            L += ["poke8 0x0203FF84 7"]
            first = False
        L += ["frames 30", "peek8 0x0203FF84 1", f"peek PARTY+{E:#x} 7"] + moves(n, 2, ab)
    L += ["echo == player 1 alone on slot 7", "p2 off", "poke8 PARTY 7"]
    for n in names:
        row = rows[n][0]
        ab, p = k[n]
        L += [f"echo == P1 {n} row {row}"] + entry(row, ab, p) + warp(0x1D0) + ["peek8 PARTY 1"] + moves(n, 1, ab)
    L += ["keys 0", "map", "ents"]
    open(os.path.join(HERE, "tny_play.txt" if not only else "tny_play_sub.txt"), "w", newline="\n").write("\n".join(L) + "\n")
    print(f"{len(names)} fighters, {len(L)} lines")


if __name__ == "__main__":
    main()
