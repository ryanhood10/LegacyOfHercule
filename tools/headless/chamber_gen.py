def intro(s, lines):
    s.out("keys 0x40", "frames 60", "keys 0", "frames 110")   # up over the line, the boss walks to his mark
    s.expect(f"{SCENE[2:].lower()}: 0000000[1-9a-f]", f"peek {SCENE} 1")
    s.out("shot {}_walk".format(s.tag))
    for k in range(lines):
        s.out("frames 60", "key 1 6", "frames 50", "key 1 6", "frames 40") if False else None
    s.out(f"stepz {SCENE} 40", "frames 90")
    s.expect(f"{SCENE[2:].lower()}: 00000000", f"peek {SCENE} 1")
    s.state(r"[0-9a-f]{6}0[12]$")


