def entry(slot):
    return 0x0203F00C + slot * 0x1C


class S:
    def __init__(self, head):
        self.L = ["# GENERATED by tools/headless/chamber_gen.py", *["# " + h for h in head]]

    def out(self, *a):
        self.L.extend(a)

    def echo(self, t):
        self.out(f"echo {t}")

    def expect(self, regex, *cmd):
        self.out(f"echo EXPECT {regex}", *cmd)

    def begin(self, tag, p1=PICCOLO, p2=HERCULE, flags=LOCKED):
        self.out(f"echo === {tag}", "load menu.ss", "p2 off" if p2 is None else "p2 0", f"preset {flags}", "maptest 263", "frames 200",
                 f"poke8 0x0203F000 {p1}")
        if p2 is not None:
            self.out(f"poke8 0x0203FF84 {p2}")
        self.out("deref TBL 0x0800959C")

    def warp(self, za, x, y, frames=150):
        self.out(f"poke32 {ARG} {za:#x}", f"poke32 {ARG2} {x | y << 16:#x}", f"poke32 {CMD} 5", f"frames {frames}")

    def door(self, opening=False):
        """from the chamber room through the door: a real load of the open area (its spot records). The opening of a run plays
        only when flag 510 is clear (test command 48 op 7 sets it here unless `opening`; op 0, the lights, sets it too)"""
        self.out(f"poke32 {ARG} 7", f"poke32 {ARG2} {0 if opening else 1}", f"poke32 {CMD} 48", "frames 2")
        self.warp(0x0309, 96, 160)
        self.out("keys 0x40", "frames 20", "keys 0", "key 1 6", "waitmap 15 18 600", "frames 260")

    def chs(self, regex):
        """chamber.c ChState +0x30: the open area's scene | bits << 8 | the portal's frames << 16 | the scene's wait << 24 (read from
        RAM: test commands wait while a scene runs)"""
        self.out("find CH 0x4348414D")
        self.expect(rf"\w+: {regex}", "peek CH+0x30 1")

    def camera(self, regex):
        """the view's top-left (the camera object's +0x1C / +0x20, docs: rom.h CAMERA_CELL)"""
        self.out("deref CAM 0x081DA974")
        self.expect(rf"\w+: {regex}", "peek CAM+0x1C 2")

    def quiet(self):
        """the void's refill frozen and every standing body gone (a test of the door or the scene, not of a fight)"""
        self.out(f"poke32 {ARG} 3", f"poke32 {ARG2} 1", f"poke32 {CMD} 48", "frames 2", f"poke32 {CMD} 13", "frames 30")

    def lights(self, mask):
        self.out(f"poke32 {ARG} 0", f"poke32 {ARG2} {mask:#x}", f"poke32 {CMD} 48", "frames 2")

    def full(self, slots=(GOHAN, PICCOLO, VEGETA, TRUNKS, GOKU, HERCULE, KRILLIN)):
        for s in slots:
            self.out(f"poke16 {entry(s):#x} 999", f"poke16 {entry(s) + 2:#x} 999", f"poke16 {entry(s) + 4:#x} 400", f"poke16 {entry(s) + 6:#x} 400")

    def place(self, x, y, p2=True):
        self.out("deref P1 0x03001FA8", f"poke32 P1+0x158 {x << 8:#x}", f"poke32 P1+0x15C {y << 8:#x}")
        if p2:
            self.out("deref P2 0x0203FF08", f"poke32 P2+0x158 {(x - 16) << 8:#x}", f"poke32 P2+0x15C {y << 8:#x}")

    def deco(self, index, name="D"):
        self.out(f"deref {name} {0x03001128 + 4 * index:#x}")

    def actor(self, sprite, n):
        self.out(f"deref R{sprite} TBL+{(sprite - 7) * 4:#x}", f"echo EXPECT entrec [0-9a-f]+: {n}$", f"entrec R{sprite}")

    def state(self, regex):
        """the room's state: chamber.c ChState +4: state, timer, target, frozen (a little-endian word)"""
        self.out("find CH 0x4348414D")
        self.expect(f"[0-9a-f]+: {regex}", "peek CH+4 1")   # the state is the low byte

    def write(self, name):
        self.out("echo ALIVE")
        open(os.path.join(HERE, name), "w", newline="\n").write("\n".join(self.L) + "\n")
        print(f"{name}: {len(self.L)} lines")


