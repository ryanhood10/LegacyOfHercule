def flag_re(bit):
    """FLAGS+0x3F (flags 504-511) with flag 504 + bit set (short: the runner cuts a long EXPECT line)"""
    digits = "".join(f"{v:x}" for v in range(16) if (v >> (bit & 3)) & 1)
