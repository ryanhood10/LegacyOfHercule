def tiers():
    s = S(["Each tier by lights out, two players then one: the spots' bodies, the EXP of a kill, the refill round the players, OBJ VRAM's largest",
           "free block (the waves.obj_low method: chamber.c ChState +0x14, in 32-byte units) and frame time. Test commands 13 / 14 and the old rounds too."])
    for tier in range(7):
        for two in (True, False):
            mask = (1 << tier) - 1
            s.begin(f"tier {tier}, {'two players' if two else 'one player'}", p2=HERCULE if two else None)
            s.lights(mask)
            s.door()
            s.full()
            s.out("find CH 0x4348414D", f"poke32 {ARG} 4", f"poke32 {CMD} 48", "frames 2")
            s.echo("the tier's bodies stand (the refill keeps its record count)")
            s.out("frames 300")
            s.full()
            s.out("ents", "vram", f"perf 240 tier{tier}{'c' if two else 's'}")
            s.full()
            s.out(f"shot t_{tier}{'c' if two else 's'}")
            s.echo("every standing body is one of the tier's kinds; a body's private stat: the table's EXP, its HP (x 1.5 in co-op)")
            for sp in TIERS[tier]:
                s.out(f"deref R{sp} TBL+{(sp - 7) * 4:#x}", f"entrec R{sp}")
            s.out(f"findent EN {ENEMY_VT}", "deref ST EN+0x180")
            hps = "|".join(f"{(h * 3 // 2 if two else h):08x}" for h in HP[tier])
            s.expect(rf"\w+: {EXP[tier]:08x} ({hps})", "peek ST 2")
            s.echo("kills at level 36 pay it (the stock clamp, a 128th to a half of the level's span, lets it through)")
            s.out(f"poke32 {entry(PICCOLO) + 0x10:#x} {LEVEL36}")
            s.out(f"poke32 {CMD} 13", "frames 30")
            s.expect(rf"\w+: (?!{LEVEL36:08x})", f"peek {entry(PICCOLO) + 0x10:#x} 1")
            s.echo("the refill: bodies come back round the players, off the view, to the target")
            s.out("mash 8 40", "frames 500")
            s.full()
            s.out(f"poke32 {ARG} 1", f"poke32 {CMD} 48", "frames 2")
            want = "0[6-9a-f]" if two else "0[89a]"       # bodies at the last check: OBJ VRAM may hold tier 6's co-op back from 14
            s.expect(rf"0203fd0c: [0-9a-f]{{4}}00{want}", f"peek {ARG} 1")
            s.out("ents", "map", "shot t_{}{}_r".format(tier, "c" if two else "s"))
    s.echo("=== the old rounds' plumbing (test commands 13, 14, 48 op 5) on zone 15 area 2")
    s.begin("old rounds")
    s.warp(0x020F, 312, 280)
    s.out(f"poke32 {ARG} 5", f"poke32 {ARG2} 1", f"poke32 {CMD} 48", "frames 60", "find WV 0xC00B3A7E")
    s.echo("round 1, state 3 (fight), its enemies")
    s.expect(r"\w+: 03 01|\w+: \w+ 0[13]", "peek8 WV+0x10 2") if False else None
    s.out("peek8 WV+0x10 2")
    s.out(f"poke32 {ARG} 3", f"poke32 {CMD} 14", "frames 3", f"poke32 {CMD} 13", "frames 150")
    s.echo("the skip took: round 3 now")
    s.expect(r"\w+: 03 03", "peek8 WV+0x10 2")
    s.write("chamber_tiers.txt")


