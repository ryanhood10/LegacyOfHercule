r"""Writes the Time Chamber's self-checking scripts (docs/testing.md "Time Chamber", docs/time-chamber.md 12): chamber_gate.txt (the open
area, the door, the lights by flags, the beams, the save pad, the jars, the corners), chamber_tiers.txt (each tier's bodies, OBJ VRAM,
EXP, the refill, the old test commands), chamber_room.txt (Roshi's dojo in every kind of lineup). Run the output with staging_run.py
(st_expect plus the sanity of the `ents` lists):
  python tools/headless/chamber_gen.py
  python tools/headless/staging_run.py tools/headless/chamber_room.txt build/<dir>/log2-coop.gba build/<dir>/hl/menu.ss --out build/<dir>/hl --cols 6"""
import os

CMD, ARG, ARG2 = "0x0203FD08", "0x0203FD0C", "0x0203FD54"
