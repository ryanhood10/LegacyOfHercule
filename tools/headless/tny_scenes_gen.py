"""Write tools/headless/tny_scenes.txt: the tournament's scenes as staged (docs/tournament.md 27, docs/testing.md "Tournament
scenes"), every lineup, self-checking, with the `ents` lists checked by staging_run.py.
usage: python tools/headless/tny_scenes_gen.py     (the script is committed; rerun this after changing it here)
       python tools/headless/staging_run.py tools/headless/tny_scenes.txt build/<dir>/log2-coop.gba build/<dir>/hl/menu.ss --out build/<dir>/hl --cols 6

What it checks: while a fight's talk shows, the others on the floor face the speaker and the speaker holds his pose (a seeded
draw: Map Test 13's party, seed 42, Spopovich in the 1 v 1, Mecha Frieza and King Cold in the 2 v 2); after the talk the
fighters face each other for the call and the announcer holds his microphone facing the crowd; Start ends a talk on the box
it shows; whole tournaments of every lineup (one player, two, 2 v 2, the Rumble alone and in teams, the co-op 1 v 1 to the duel
final, the same fighter twice, tournament-only fighters, Legend's giants, a loss) end back in the waiting room with the staging's
counts (test command 38 arg 5 wipes them; `.combo.st`: lines staged, the announcer's lines, the champions' highest hop, boxes
moved to the bottom; the Rumble's lines are its hidden challenger's talk); the plaza's welcome shows the announcer and turns the players to him. Test command 40 decides every fight after 30
frames. Each block starts from the debug menu's state (`load menu.ss`: it must sit in the --out folder). Addresses: eng 0x0203EC00 (+4 phase, +0x2C the opponents, +0xFD t_busy, +0x11C the held poses' bodies, +0x12C their
groups (0x80 standing, 0x40 one line's), +0x14C the announcer, +0x152 the poses held); an entity's facing is +0x10 (0 down, 1 up,
2 left, 3 right); player 1 0x03001FA8, player 2 0x0203FF08."""
import os

ENG = 0x0203EC00
PHASE, BUSY, NPOSE, POSEG, ANN, OPP = "0x0203EC04", "0x0203ECFD", "0x0203ED52", "0x0203ED2C", "0x0203ED4C", "0x0203EC2C"
P1, P2 = "0x03001FA8", "0x0203FF08"
TF_YAMCHA, TF_YAMU, TF_PICCOLO = 0, 9, 52
L = []


def out(*lines):
    L.extend(lines)


def cmd(n, a=0, b=0):
    out(f"poke32 0x0203FD0C {a:#x}", f"poke32 0x0203FD54 {b:#x}", f"poke32 0x0203FD08 {n}", "frames 10")


def expect(regex, *line):
    out(f"echo EXPECT {regex}", *line)


def start(p2=False, tiers=0, flags=2, unlock=(), lose=0, duel=0):
    """Map Test 13, player 2 in or not, stand-in bodies for missing art, the record wiped, seed 42, in front of the director,
    fights decided after 30 frames, the staging's counts wiped."""
    out("load menu.ss", "p2 0" if p2 else "p2 off", "maptest 13", "frames 300")
    if p2:
        out("frames 200")
    cmd(24, tiers, flags)
    cmd(23, 0)
    for fid in unlock:
        cmd(23, 1, fid)
    cmd(21, 42)
    out("poke32 0x0203FD0C 0x0F0F", "poke32 0x0203FD54 0x013200A8", "poke32 0x0203FD08 5", "frames 300")
    cmd(40, 30, lose | duel << 24)
    cmd(38, 5)
    out("find ST 0x47415453")


def go(div, tier=0, pick1=0xFF, pick2=0xFF, full=0):
    cmd(25, div | full << 4 | tier << 8, pick1 | pick2 << 8)


def finish(name, steps=250):
    """A on both pads until the tournament is over; back in the waiting room, nothing held; the counts"""
    out(f"stepz {BUSY} {steps}", "frames 30", "map", "ents", f"shot {name}_end")
    expect("map zone 15 area 15", "map")
    expect(r"0203ec04: 00", f"peek8 {PHASE} 1")
    expect(r"0203ed52: 00", f"peek8 {NPOSE} 1")


def counts(regex, why):
    out(f"echo the staging's counts ({why}): lines, the announcer's lines, the highest hop, boxes at the bottom")
    expect(regex, "peek8 ST+4 4")


def facing(var, addr, value, why):
    out(f"deref {var} {addr}", f"echo {why}")
    expect(r"[0-9a-f]{8}: " + value, f"peek8 {var}+0x10 1")


out("# The tournament's scenes as staged (docs/tournament.md 27, docs/testing.md \"Tournament scenes\"). GENERATED by",
    "# tools/headless/tny_scenes_gen.py. Self-checking, `ents` lists checked (regfull.sh):",
    "#   python tools/headless/staging_run.py tools/headless/tny_scenes.txt build/<dir>/log2-coop.gba build/<dir>/hl/menu.ss --out build/<dir>/hl --cols 6",
    "# ST = `.combo.st` (+4 lines staged, the announcer's lines, the champions' highest hop in px, boxes moved to the bottom).")

# ---- A. one player, Rookie 1 v 1, his own character (the debug party's Piccolo) against Spopovich --------------------------
out("echo === A. 1P Rookie 1 v 1: the talk, line by line; the call; the whole tournament")
start()
go(0)
out("waitnz ST+4 3000", "frames 24", "ents", "shot a1_line0")
out("echo line 0: Spopovich opens; the announcer turns right to him, he turns left to Piccolo, Piccolo looks at him, Spopovich poses")
expect(r"[0-9a-f]{8}: 01 00", "peek8 ST+4 2")
facing("AN", ANN, "03", "the announcer faces right, to the speaker")
facing("O0", OPP, "02", "the speaker faces left, to the player")
facing("PA", P1, "03", "player 1 faces right, to the speaker")
expect(r"0203ed52: 01", f"peek8 {NPOSE} 1")
expect(r"0203ed2c: c[45e]", f"peek8 {POSEG} 1")
out("frames 70", "key 1 6", "frames 30", "ents", "shot a2_line1")
out("echo line 1: Piccolo answers; the announcer turns left to him, Piccolo poses, Spopovich lets his pose go and listens")
expect(r"[0-9a-f]{8}: 02 00", "peek8 ST+4 2")
facing("AN", ANN, "02", "the announcer faces left, to the speaker")
facing("O0", OPP, "02", "Spopovich faces Piccolo")
expect(r"0203ed52: 01", f"peek8 {NPOSE} 1")
expect(r"0203ed2c: c[45e]", f"peek8 {POSEG} 1")
out("frames 70", "key 1 6", "frames 60", "shot a3_call")
out("echo the call: squared up (player right, opponent left), the announcer to the crowd with his microphone (group 4, one line)")
expect(r"[0-9a-f]{8}: 02 01", "peek8 ST+4 2")
facing("AN", ANN, "00", "the announcer faces the crowd")
facing("PA", P1, "03", "player 1 faces right")
facing("O0", OPP, "02", "the opponent faces left")
expect(r"0203ed52: 01", f"peek8 {NPOSE} 1")
expect(r"0203ed2c: c4", f"peek8 {POSEG} 1")
finish("a")
counts(r"[0-9a-f]{8}: ([0-9a-f][0-9a-f]) ([0-9a-f][0-9a-f]) 06", "a won 1 v 1: the champion hopped 6 px")

# ---- B. two players, Rookie 2 v 2: Piccolo and player 2's own character against Mecha Frieza and King Cold -------------------
out("echo === B. 2P Rookie 2 v 2: the partners look at each other, the other side looks across")
start(p2=True)
go(1)
out("waitnz ST+4 3000", "frames 24", "ents", "shot b1_line0")
out("echo line 0: Mecha Frieza opens (upper right): King Cold below him looks up, player 2 looks right")
facing("O1", "0x0203EC30", "01", "King Cold faces up, to his partner")
facing("PB", P2, "03", "player 2 faces right")
facing("AN", ANN, "03", "the announcer faces right")
out("frames 70", "key 1 6", "frames 30", "ents", "shot b2_line1")
out("echo line 1: Piccolo answers (upper left): player 2 below him looks up, both opponents look left")
facing("PB", P2, "01", "player 2 faces up, to his partner")
facing("O0", OPP, "02", "Mecha Frieza faces left")
facing("O1", "0x0203EC30", "02", "King Cold faces left")
expect(r"[0-9a-f]{8}: 02 00 00 0[0-2]", "peek8 ST+4 4")
out("echo (the box of Piccolo's line went to the bottom: he stands in the view's upper part)")
finish("b")
counts(r"[0-9a-f]{8}: [0-9a-f]{2} [0-9a-f]{2} 06", "a won 2 v 2: the champions hopped")

# ---- C. two players, co-op 1 v 1 to the duel final (player 2 wins it) -----------------------------------------------------
out("echo === C. 2P co-op 1 v 1: the turns, the duel final's talk (player 2 opens, player 1 answers), player 2 the champion")
start(p2=True, duel=2)
go(0)
finish("c", 300)
counts(r"[0-9a-f]{8}: ([1-9a-f][0-9a-f]|0[6-9a-f]) [0-9a-f]{2} 06", "every fight's talk staged; the champion hopped")

# ---- D. one player, Rookie Royal Rumble: no talk, the announcer's calls ----------------------------------------------------
out("echo === D. 1P Rookie Royal Rumble: the announcer's calls with his microphone, no fighters' lines")
start()
go(2)
finish("d")
counts(r"[0-9a-f]{8}: [0-9a-f]{2} ([0-9a-f][1-9a-f]|[1-9a-f]0) 06", "calls; the champion hopped (lines: the hidden challenger's talk)")

# ---- E. two players, Rookie Royal Rumble (2 v 2 v 2) -----------------------------------------------------------------------
out("echo === E. 2P Rookie Royal Rumble")
start(p2=True)
go(2)
finish("e")
counts(r"[0-9a-f]{8}: [0-9a-f]{2} ([0-9a-f][1-9a-f]|[1-9a-f]0) 06", "calls; the champions hopped")

# ---- F. the same fighter twice: both players on Piccolo, 2 v 2 -----------------------------------------------------------------
out("echo === F. 2P 2 v 2, both players on Piccolo (player 2 in the shadow)")
start(p2=True)
go(1, pick1=TF_PICCOLO, pick2=TF_PICCOLO)
out("waitnz ST+4 3000", "frames 24", "ents", "shot f1_line0")
finish("f")
counts(r"[0-9a-f]{8}: [0-9a-f]{2} [0-9a-f]{2} 06", "the twins win")

# ---- G. tournament-only fighters as players: Yamu and Yamcha, 2 v 2 ------------------------------------------------------------
out("echo === G. 2P 2 v 2 on Yamu and Yamcha (tournament-only bodies)")
start(p2=True, unlock=(TF_YAMU, TF_YAMCHA))
go(1, pick1=TF_YAMU, pick2=TF_YAMCHA)
out("waitnz ST+4 3000", "frames 24", "ents", "shot g1_line0")
finish("g")
counts(r"[0-9a-f]{8}: [0-9a-f]{2} [0-9a-f]{2} 06", "they win")

# ---- H. one player, Legend 1 v 1 (the giants' bodies) --------------------------------------------------------------------------
out("echo === H. 1P Legend 1 v 1 (every tier open, story flags ignored): giants' bodies talk and pose")
start(tiers=0x1F, flags=3)
go(0, tier=4)
out("waitnz ST+4 3000", "frames 24", "ents", "shot h1_line0")
finish("h", 300)
counts(r"[0-9a-f]{8}: [0-9a-f]{2} [0-9a-f]{2} 06", "Legend won")

# ---- I. a loss, and Start on a talk ----------------------------------------------------------------------------------------------
out("echo === I. 1P Rookie 1 v 1 lost in the first round; Start on the first line ends the talk there")
start(lose=1)
go(0)
out("waitnz ST+4 3000", "frames 24", "key 8 6", "frames 10", "key 1 6", "frames 60", "shot i1_call")
out("echo after Start and A: one line staged, the call is up")
expect(r"[0-9a-f]{8}: 01 01", "peek8 ST+4 2")
finish("i")
counts(r"[0-9a-f]{8}: 0[1-9a-f] 0[2-9a-f] 00", "lost: the winner's line, the result call, no hop")

# ---- J. the plaza's welcome, one player and two ------------------------------------------------------------------------------------
for p2 in (False, True):
    tag = "j2" if p2 else "j1"
    out(f"echo === J. the plaza's welcome ({'two players' if p2 else 'one player'}): the players turn to the announcer")
    out("load menu.ss", "p2 0" if p2 else "p2 off", "maptest 176", "waitmap 6 99 2000", "frames 60", "flags -441")
    out("poke32 0x0203FD0C 0x6306", "poke32 0x0203FD54 0x071C04EC", "poke32 0x0203FD08 5", "frames 150", "key 1 10",
        "waitmap 15 11 600", "frames 200", f"shot {tag}_caption", "key 1 10", "frames 90", "ents", f"shot {tag}_welcome")
    facing("PA", P1, "03", "player 1 faces right, to the announcer (up and right of the landing)")
    if p2:
        facing("PB", P2, "03", "player 2 too")
    for _ in range(12):
        out("key 1 10", "frames 60")
    out("frames 60", "map", "ents", f"shot {tag}_after")
    expect("map zone 15 area 11", "map")
    out("echo flag 441 set")
    expect(r"[0-9a-f]{8}: [0-9a-f][2367abef]", "peek8 FLAGS+0x37")

open(os.path.join(os.path.dirname(os.path.abspath(__file__)), "tny_scenes.txt"), "w", newline="\n").write("\n".join(L) + "\n")
print(f"wrote tny_scenes.txt: {len(L)} lines")
