ENG = 0x0203EC00
PHASE, BUSY, NPOSE, POSEG, ANN, OPP = "0x0203EC04", "0x0203ECFD", "0x0203ED52", "0x0203ED2C", "0x0203ED4C", "0x0203EC2C"
P1, P2 = "0x03001FA8", "0x0203FF08"
