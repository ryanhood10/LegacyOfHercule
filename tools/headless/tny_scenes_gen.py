TALK = 0x4B4C4154                       # `.tny.talk`'s magic: +0x58 the lines, line i's speaker seat at +0x31 + 12 i
L = []


def out(*lines):
    L.extend(lines)


def cmd(n, a=0, b=0):
    out(f"poke32 0x0203FD0C {a:#x}", f"poke32 0x0203FD54 {b:#x}", f"poke32 0x0203FD08 {n}", "frames 10")


def expect(regex, *line):
    out(f"echo EXPECT {regex}", *line)


def start(p2=False, tiers=0, flags=2, unlock=(), lose=0, duel=0):
    """Map Test 13, player 2 in or not, stand-in bodies for missing art, the record wiped, seed 42, in front of the director,
    fights decided after 30 frames, the staging's counts wiped."""
    out("load menu.ss", "p2 0" if p2 else "p2 off", "maptest 13", "frames 300")
    if p2:
        out("frames 200")
    cmd(24, tiers, flags)
    cmd(23, 0)
    for fid in unlock:
        cmd(23, 1, fid)
    cmd(21, 42)
    out("poke32 0x0203FD0C 0x0F0F", "poke32 0x0203FD54 0x013200A8", "poke32 0x0203FD08 5", "frames 300")
    cmd(40, 30, lose | duel << 24)
    cmd(38, 5)
    out("find ST 0x47415453")


def go(div, tier=0, pick1=0xFF, pick2=0xFF, full=0):
    cmd(25, div | full << 4 | tier << 8, pick1 | pick2 << 8)


def finish(name, steps=250):
    """A on both pads until the tournament is over; back in the waiting room, nothing held; the counts"""
    out(f"stepz {BUSY} {steps}", "frames 30", "map", "ents", f"shot {name}_end")
    expect("map zone 15 area 15", "map")
    expect(r"0203ec04: 00", f"peek8 {PHASE} 1")
    expect(r"0203ed52: 00", f"peek8 {NPOSE} 1")


def counts(regex, why):
    out(f"echo the staging's counts ({why}): lines, the announcer's lines, the highest hop, boxes at the bottom")
    expect(regex, "peek8 ST+4 4")


def facing(var, addr, value, why):
    out(f"deref {var} {addr}", f"echo {why}")
    expect(r"[0-9a-f]{8}: " + value, f"peek8 {var}+0x10 1")


