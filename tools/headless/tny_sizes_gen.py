r"""Write tools/headless/tny_sizes.txt: "How many fighters?" after the division, every division, and what each size builds (docs/tournament.md "Sizes").
usage: python tools/headless/tny_sizes_gen.py     (the script is committed; rerun this after changing it here)
Two players by pad presses on the story's flags; the Rumble's pairs: real fights for a crash, both players mashing. eng 0x0203EC00: phase +4, the bracket +0x6C (size, rounds, round, match; seats +4),
rb_round / rb_rounds: read off the announcer's screen in the shots. Test command 40 ends the others' fights."""
import os

L = ["# GENERATED by tools/headless/tny_sizes_gen.py", "p2 0"]
BR = 0x0203EC6C
BUSY = "0x0203ECFD"
NOFIGHT = "0x0203ECFC"
LEGEND = [85, 127, 136, 146, 191, 301, 402, 421, 382]


def out(*a):
    L.extend(a)


def cmd(n, a=0, b=0):
    out(f"poke32 0x0203FD0C {a:#x}", f"poke32 0x0203FD54 {b:#x}", f"poke32 0x0203FD08 {n}", "frames 10")


def p1(mask):
    out(f"key {mask:#x} 6", "frames 80")


def p2(mask):
    out(f"p2 {mask:#x}", "frames 4", "p2 0", "frames 80")


def menus(tier, flags, div, size, seed, tag, decide=True):
    """To the bracket: the tier, the division (0 1 v 1, 1 2 v 2, 2 Rumble), a shot of the size menu, the size, both picks."""
    out("load menu.ss", "p2 0", "maptest 13", "frames 300")
    cmd(23, 0)
    if decide:
        cmd(40, 30, 0)
    cmd(21, seed)
    if flags:
        out("flags " + " ".join(f"+{f}" for f in flags), "frames 4")
    cmd(5, 15 | 15 << 8, 168 | 306 << 16)
    out("frames 190", "key 0x80 6", "key 1 10", "frames 60", "key 1 6", "frames 60", "key 1 6", "frames 80")
    for _ in range(tier):
        out("key 0x80 6", "frames 20")
    p1(1)
    for _ in range(div):
        out("key 0x80 6", "frames 20")
    p1(1)
    out(f"shot {tag}_menu")
    for _ in range(size):
        out("key 0x80 6", "frames 20")
    p1(1)
    p1(1)
    p2(1)


out("echo === Rookie: 16 is locked, a press on it stays on the menu; 8 fighters, 3 rounds")
menus(0, [], 0, 1, 42, "rk")
out("shot rk_locked", r"echo EXPECT 0203ec04: 01", "peek8 0x0203EC04 1")
out("echo === Legend 1 v 1, 16 fighters: 16 seats, 4 rounds")
menus(4, LEGEND, 0, 1, 42, "l1")
out("frames 100", "shot l1_bracket", r"echo EXPECT 0203ec6c: 10 04", f"peek8 {BR:#x} 2", f"stepz {BUSY} 400", "frames 30", "map")
out("echo === Legend 2 v 2, 8 fighters: 4 teams, 2 rounds")
menus(4, LEGEND, 1, 0, 42, "l2q")
out("frames 100", "shot l2q_bracket", r"echo EXPECT 0203ec6c: 08 02", f"peek8 {BR:#x} 2", f"stepz {BUSY} 300", "frames 30", "map")
out("echo === Legend 2 v 2, 16 fighters: 8 teams, 3 rounds")
menus(4, LEGEND, 1, 1, 42, "l2f")
out("frames 100", "shot l2f_bracket", r"echo EXPECT 0203ec6c: 10 03", f"peek8 {BR:#x} 2", "frames 200", "shot l2f_bracket2", f"stepz {BUSY} 400", "frames 30", "shot l2f_end", "map")
for tier, flags, name in ((0, [], "Rookie"), (2, [85, 127, 136], "ZFighter"), (4, LEGEND, "Legend")):
    for size in (0, 1) if tier else (0,):
        out(f"echo === {name} Rumble, {16 if size else 8} fighters: 2 v 2 v 2, real fights")
        tag = f"r{tier}{size}"
        menus(tier, flags, 2, size, 42, tag, decide=False)
        out("frames 40", f"shot {tag}_board0", "frames 60", f"shot {tag}_board1", "key 1 6", "frames 60", "key 1 6", "frames 200", f"stepz {NOFIGHT} 200", "frames 40", f"shot {tag}_fight", "ents")
        for k in range(90):
            out("keys 1", "frames 4", "keys 0", "frames 4", "p2 1", "frames 4", "p2 0", "frames 4")
        out(f"shot {tag}_fight2", "map", "ents")
# one player: the division list has no 2 v 2 (1 v 1, Rumble); 16 fighters in a Rumble, real fights for a crash
for tier, flags, name in ((0, [], "Rookie"), (4, LEGEND, "Legend")):
    size = 1 if tier else 0
    out(f"echo === one player, {name} Rumble, {16 if size else 8} fighters", "load menu.ss", "p2 off", "maptest 13", "frames 300")
    cmd(23, 0)
    cmd(21, 42)
    if flags:
        out("flags " + " ".join(f"+{f}" for f in flags), "frames 4")
    cmd(5, 15 | 15 << 8, 168 | 306 << 16)
    out("frames 190", "key 0x80 6", "key 1 10", "frames 60", "key 1 6", "frames 60", "key 1 6", "frames 80")
    for _ in range(tier):
        out("key 0x80 6", "frames 20")
    p1(1)
    out("key 0x80 6", "frames 20")
    p1(1)
    for _ in range(size):
        out("key 0x80 6", "frames 20")
    p1(1)
    p1(1)
    tag = f"s{tier}"
    out("frames 60", f"shot {tag}_board", "key 1 6", "frames 60", "key 1 6", "frames 200", f"stepz {NOFIGHT} 200", "frames 40", f"shot {tag}_fight", "ents")
    for k in range(60):
        out("keys 1", "frames 6", "keys 0", "frames 6")
    out(f"shot {tag}_fight2", "map")
out("echo DONE")
here = os.path.dirname(os.path.abspath(__file__))
open(os.path.join(here, "tny_sizes.txt"), "w", newline="\n").write("\n".join(L) + "\n")
print(f"tny_sizes.txt: {len(L)} lines")
