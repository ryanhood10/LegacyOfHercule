r"""Shared by the staging_ch*_gen.py generators (docs/testing.md "Scene staging"): one scene per lineup, from a debug-menu
savestate. Each scene Map Tests an inert map (entry 7), pokes who plays, warps into the scene's trigger, and checks that the
actors stand (or do not) by their sprite records (the table at *0x0800959C, entry id - 7), that the scene ends (a scene that
hung would leave the expect to fail) and which map it ended on. Run the output with staging_run.py: it adds the
sanity of the `ents` lists (an actor animated on a pose group its sprite does not have corrupts the heap, docs/sprites.md: the
runner keeps going after that, so "no CRASH" is not enough)."""
import os

SCENE = "0x03001FDC"            # a dialogue sequence runs
CMD, ARG, ARG2 = "0x0203FD08", "0x0203FD0C", "0x0203FD54"
HERE = os.path.dirname(os.path.abspath(__file__))
# party slots
GOHAN, PICCOLO, VEGETA, TRUNKS, GOKU, HERCULE, KRILLIN, A16, SS2 = range(9)
NAMES = "GPVTOHKAS"


def flags_of(slot):             # the party entry's flags byte
    return f"{0x0203F020 + slot * 0x1C:#x}"


def lineup_name(p1, p2):
    return NAMES[p1] + ("" if p2 is None else NAMES[p2])


class Script:
    def __init__(self, gen):
        self.L = [f"# GENERATED by tools/headless/{gen}"]
        self.gen = gen

    def out(self, *a):
        self.L.extend(a)

    def begin(self, tag, p1, p2=None, preset="", pokes=(), maptest=7):
        """p2 None: one player. Ends on the inert map, nobody warped yet."""
        self.out(f"echo === {tag}", "load menu.ss", "p2 off" if p2 is None else "p2 0")
        if preset:
            self.out(f"preset {preset}")
        self.out(f"maptest {maptest}", "frames 200", f"poke8 0x0203F000 {p1}")
        if p2 is not None:
            self.out(f"poke8 0x0203FF84 {p2}")
        self.out(*pokes)
        self.out("deref TBL 0x0800959C")

    def warp(self, zone, area, x, y, frames=300):
        self.out(f"poke32 {ARG} {zone | area << 8:#x}", f"poke32 {ARG2} {x | y << 16:#x}", f"poke32 {CMD} 5", f"frames {frames}")

    def actors(self, **want):
        """s76=1: entities on sprite 76's record. Players count: a player on that very record shows too (Gohan's slot shows sprite 53)."""
        for k, n in want.items():
            sp = int(k[1:])
            self.out(f"deref R{sp} TBL+{(sp - 7) * 4:#x}", f"echo EXPECT entrec [0-9a-f]+: {n}$", f"entrec R{sp}")

    def press(self, n, gap=100):
        self.out(f"mash {n} {gap}")

    def shot(self, name):
        self.out(f"shot {name}")

    def end_scene(self, mx=150):
        self.out(f"stepz {SCENE} {mx}", "frames 30", f"echo EXPECT {SCENE[2:].lower()}: 00000000", f"peek {SCENE} 1")

    def win(self, frames=240):
        self.out(f"poke32 {CMD} 7", f"frames {frames}")

    def cine_last(self, op, how=1):
        """the cine helpers' last move was `op` and it ended `how` (1 played, 2 skipped: cine.c END_*), and every move started has
        ended (CineRam +0x0C's top byte, +0x10's low byte, +0x18 ops = done; docs/testing.md "Cinematic helpers")"""
        self.out("find CN 0xC14E0001",
                 f"echo EXPECT [0-9a-f]{{8}}: {op:02x}[0-9a-f]{{6}} [0-9a-f]{{6}}{how:02x}", "peek CN+0x0C 2",
                 r"echo EXPECT [0-9a-f]{8}: ([0-9a-f]{4})\1", "peek CN+0x18 1")

    def on_map(self, zone, area):
        self.out(f"echo EXPECT map zone {zone} area {area}\\b", "map", "ents")

    def write(self, name):
        self.out("echo ALIVE")
        open(os.path.join(HERE, name), "w", newline="\n").write("\n".join(self.L) + "\n")
        print(f"{name}: {len(self.L)} lines")
