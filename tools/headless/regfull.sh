#!/bin/bash
# The full headless regression (docs/testing.md "Full regression"): every chapter and tournament script on a
# DEBUG_MENU=1 build in both modes (co-op as written; arctic_summit, postgame and ch9_gero again with player 2 off),
# then the prologue on the play ROM. Pass: no TIMEOUT / CRASH / FAIL line in the log.
#   make BUILD=build/<dir> DEBUG_MENU=1 && make
#   python tools/headless/st_test.py tools/headless/mkmenu.txt build/<dir>/log2-coop.gba --out build/<dir>/hl
#   bash tools/headless/regfull.sh build/<dir>        (default build/tny; about 15 minutes)
#   PLAY=build/<dir>/play/log2-coop.gba bash ...     the play ROM for the prologue (default build/log2-coop.gba)
#   grep -nE "TIMEOUT|CRASH|FAIL" build/<dir>/hl/reg.log
cd "$(dirname "$0")/../.." || exit 1
DIR=${1:-build/tny}
ROM=$DIR/log2-coop.gba; PLAY=${PLAY:-build/log2-coop.gba}; OUT=$DIR/hl; LOG=$OUT/reg.log; : > "$LOG"
run() { echo "## $1" >> "$LOG"; python tools/headless/st_test.py "$2" "$ROM" "$OUT/menu.ss" --out "$OUT" --cols 6 2>&1 | grep -E "^==|^map zone|^0[0-9a-f]{7}:|entrec|reached|stepnz|FAIL|rror|TIMEOUT|CRASH" >> "$LOG"; }
for t in a16_moves tny_eggs tny_crowd tny_npcs tny_polish tny_engine tny_ui tny_moves tny_rumble tny_play tny_artnew \
         tny_artbuu tny_grounds cell_games cell_games_1p krillin_disc arctic_summit postgame ch9_gero p2_special revive difficulty \
         journal dropout ch1_room_forest scene_actor exp_credit a16_gone broly_ride duel_end tny_hpbars tny_fightfix \
         tny_nomirror tny_talk tny_combo_draw tny_combo_meter tny_combo_run tny_combo_tune wm_landmark tny_pp_combo \
         tny_caption tny_annwalk tny_turn tny_walk cell_juniors ch9_actors ch1_notes player_lines lead_scenes; do
  run $t tools/headless/$t.txt
done
for t in arctic_summit postgame ch9_gero; do
  sed -e 's/^p2 0$/p2 off/' -e '/^p2 [^o]/d' tools/headless/$t.txt > "$OUT/${t}_1p.txt"
  run ${t}_1p "$OUT/${t}_1p.txt"
done
# Super Saiyan Hercule (docs/testing.md "Super Saiyan Hercule"): self-checking, st_expect.py prints FAIL on a mismatch
echo "## ssj_hercule" >> "$LOG"
python tools/headless/st_expect.py tools/headless/ssj_hercule.txt "$ROM" "$OUT/menu.ss" --out "$OUT" --cols 6 2>&1   | grep -E "^==|^map zone|^0[0-9a-f]{7}:|FAIL|rror|TIMEOUT|CRASH" >> "$LOG"
# A soft reset, then a two-player load, a one-player load and a new game (docs/testing.md "Soft reset"): self-checking
echo "## softreset" >> "$LOG"
python tools/headless/st_expect.py tools/headless/softreset.txt "$ROM" "$OUT/menu.ss" --out "$OUT" --cols 4 2>&1   | grep -E "^==|^map zone|^0[0-9a-f]{7}:|FAIL|rror|TIMEOUT|CRASH" >> "$LOG"
# Resting heals, player 2's pickups, West City's arrival, the tournament in co-op, player 2's agency (docs/testing.md "Resting heals", "Player 2's pickups", "West City's arrival", "Tournament in co-op", "Player 2's agency"): self-checking
for t in regen pickup wc_arrival corn_maze ssj_lock hercule_kit tny_coop p2_agency p2_cases p2_scenes balance p2_levelup tny_pools tny_xp eggbot tny_sizes ch4_eggs ch4_staging tny_bracket tny_n32 cell_staging gohan_ssj1 hercule_fly hercule_shoot summit_flight; do
  echo "## $t" >> "$LOG"
  python tools/headless/st_expect.py tools/headless/$t.txt "$ROM" "$OUT/menu.ss" --out "$OUT" --cols 4 2>&1   | grep -E "^==|^map zone|^0[0-9a-f]{7}:|FAIL|rror|TIMEOUT|CRASH" >> "$LOG"
done
# The frame budget, West City's arrival, the eviction, the plaza's sign (docs/testing.md "Frame time and OAM probe"): self-checking
echo "## perf_budget" >> "$LOG"
python tools/headless/perf_budget.py "$ROM" "$OUT/menu.ss" --out "$OUT" 2>&1 | grep -E "^==|^perf |FAIL|rror|TIMEOUT|CRASH" >> "$LOG"
# Scene staging per lineup (docs/testing.md "Scene staging"): self-checking, the `ents` lists' sanity too (staging_run.py)
for s in tools/headless/staging_*.txt; do
  echo "## $(basename "$s" .txt)" >> "$LOG"
  python tools/headless/staging_run.py "$s" "$ROM" "$OUT/menu.ss" --out "$OUT" --cols 6 2>&1 | grep -E "^==|^map zone|^0[0-9a-f]{7}:|FAIL|rror|TIMEOUT|CRASH" >> "$LOG"
done
# The tournament's scenes as staged, every lineup (docs/testing.md "Tournament scenes"): self-checking, the `ents` lists too
echo "## tny_scenes" >> "$LOG"
python tools/headless/staging_run.py tools/headless/tny_scenes.txt "$ROM" "$OUT/menu.ss" --out "$OUT" --cols 6 2>&1 | grep -E "^==|^map zone|^0[0-9a-f]{7}:|FAIL|rror|TIMEOUT|CRASH" >> "$LOG"
# The Time Chamber (docs/testing.md "Time Chamber"): the open area and gate, each tier, Roshi's dojo in every kind of lineup, the five
# other rooms (one and two players, transformed, the sixth lever through the lab), Mr. Popo's room, a real save's load
for t in chamber_run chamber_gate chamber_tiers chamber_room chamber_rooms chamber_popo; do
  echo "## $t" >> "$LOG"
  python tools/headless/staging_run.py tools/headless/$t.txt "$ROM" "$OUT/menu.ss" --out "$OUT" --cols 6 2>&1 | grep -E "^==|^map zone|^0[0-9a-f]{7}:|FAIL|rror|TIMEOUT|CRASH" >> "$LOG"
done
# The cinematic helpers (docs/testing.md "Cinematic helpers"; generated by cine_gen.py): every op of CoopCall 37 for seven pairs of
# sprites, missing bodies, the players as parties, a transformed player, a skip, the demo scene in both modes
echo "## cine" >> "$LOG"
python tools/headless/staging_run.py tools/headless/cine.txt "$ROM" "$OUT/menu.ss" --out "$OUT" --cols 6 2>&1 | grep -E "^==|^map zone|FAIL|rror|TIMEOUT|CRASH" >> "$LOG"
echo "## chamber_save" >> "$LOG"
python tools/headless/chamber_save.py load "$ROM" "${SAVE:-F:/MeltyCreations/log2/build/play/legacy-of-hercule.sav}" --out "$OUT" 2>&1 | grep -E "^slot|FAIL|skipped|^chamber_save|rror|TIMEOUT|CRASH" >> "$LOG"
echo "## prologue (play ROM)" >> "$LOG"
python tools/headless/st_test.py tools/headless/prologue_companion.txt "$PLAY" --out "$DIR/play" 2>&1 | grep -E "^==|^0[0-9a-f]{7}:|stepnz|rror" >> "$LOG"
echo done >> "$LOG"
grep -c "^## " "$LOG"
if grep -nE "TIMEOUT|CRASH|FAIL" "$LOG"; then exit 1; fi   # a failure: exit 1; clean: exit 0
