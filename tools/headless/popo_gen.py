r"""Writes tools/headless/chamber_popo.txt (self-checking; docs/testing.md "Time Chamber: Mr. Popo", docs/time-chamber.md 12.7): the hidden
room behind the gate in one and two players and several characters: the way in (open only with all six lights out), the scene by
lineup, the door sealed, his far hops and dodges, the fight won by the test autopilot or by test command 7, the arms out and the end
scene, the first reward and a later one, the loop's question answered no and yes (lights back on, a time round, every boss a step
stronger), a room's prize (the first win's capsule, a Senzu once round), the big jars. Run with staging_run.py:
  python tools/headless/popo_gen.py
  python tools/headless/staging_run.py tools/headless/chamber_popo.txt build/<dir>/log2-coop.gba build/<dir>/hl/menu.ss --out build/<dir>/hl --cols 6
popo_gen.py --balance writes chamber_popo_bal.txt instead (not in regfull: the autopilot's fights for the balance numbers)."""
import os
import sys

CMD, ARG, ARG2 = "0x0203FD08", "0x0203FD0C", "0x0203FD54"
HERE = os.path.dirname(os.path.abspath(__file__))
SCENE = "0x03001FDC"
GOHAN, PICCOLO, VEGETA, TRUNKS, GOKU, HERCULE, KRILLIN, A16, SS2 = range(9)
LOCKED = "+143 +144 +148 +149 +151 +154 +157"        # the ten-day wait's flags (chamber_gen.py's)
OPEN = 0x120F                                         # zone 15 | area 18 << 8
POPO_SPRITE = 163
SENZU, STR3, PWR3, END3 = 0x0203F17F, 0x0203F182, 0x0203F185, 0x0203F188   # item counters 0, 3, 6, 9 (PartyState +0x12B + 0x54)
# popo.c states
P_WAIT, P_SCENE, P_ARMED, P_FIGHT, P_YIELD, P_OUTRO, P_DONE = 1, 2, 3, 4, 5, 6, 7


def entry(slot):
    return 0x0203F00C + slot * 0x1C


class S:
    def __init__(self, head):
        self.L = ["# GENERATED by tools/headless/popo_gen.py", *["# " + h for h in head]]
        self.tag = "x"

    def out(self, *a):
        self.L.extend(a)

    def echo(self, t):
        self.out(f"echo {t}")

    def expect(self, regex, *cmd):
        self.out(f"echo EXPECT {regex}", *cmd)

    def begin(self, title, p1, p2, tag=None):
        self.tag = tag or title.split()[0].rstrip(":")
        self.out(f"echo === {title}", "load menu.ss", "p2 off" if p2 is None else "p2 0", f"preset {LOCKED}", "maptest 263", "frames 200",
                 f"poke8 0x0203F000 {p1}")
        if p2 is not None:
            self.out(f"poke8 0x0203FF84 {p2}")
        self.out("deref TBL 0x0800959C")

    def cmd(self, n, a=0, b=0, frames=2):
        self.out(f"poke32 {ARG} {a:#x}", f"poke32 {ARG2} {b:#x}", f"poke32 {CMD} {n}", f"frames {frames}")

    def popo(self, op, b=0):
        self.cmd(49, op, b)

    def popo_expect(self, op, regex, b=0):
        self.popo(op, b)
        self.expect(rf"0203fd0c: {regex}", f"peek {ARG} 1")

    def state(self, st):
        self.out("find PO 0x4F504F50")
        self.expect(rf"\w+: 0{st}", "peek8 PO+4 1")

    def lights(self, mask):
        self.cmd(48, 0, mask)

    def warp(self, za, x, y, frames=150):
        self.cmd(5, za, x | y << 16, frames)

    def door(self):
        """from the chamber room through the door: a real load of the open area"""
        self.warp(0x0309, 96, 160)
        self.out("keys 0x40", "frames 20", "keys 0", "key 1 6", "waitmap 15 18 600", "frames 260")

    def place(self, x, y, p2=True):
        self.out("deref P1 0x03001FA8", f"poke32 P1+0x158 {x << 8:#x}", f"poke32 P1+0x15C {y << 8:#x}")
        if p2:
            self.out("deref P2 0x0203FF08", f"poke32 P2+0x158 {(x - 16) << 8:#x}", f"poke32 P2+0x15C {y << 8:#x}")

    def full(self, slots=(GOHAN, PICCOLO, VEGETA, TRUNKS, GOKU, HERCULE, KRILLIN)):
        for s in slots:
            self.out(f"poke16 {entry(s):#x} 9999", f"poke16 {entry(s) + 2:#x} 9999", f"poke16 {entry(s) + 4:#x} 400", f"poke16 {entry(s) + 6:#x} 400")

    def deco(self, index, shown):
        self.out(f"deref D {0x03001128 + 4 * index:#x}")
        self.expect(rf"\w+: 0000000{shown}", "peek D+0x10 1")

    def actor(self, n):
        self.out(f"deref R TBL+{(POPO_SPRITE - 7) * 4:#x}", f"echo EXPECT entrec [0-9a-f]+: {n}$", "entrec R")

    def flag(self, n, on):
        self.out(f"echo flag {n} {'set' if on else 'clear'}")
        bit = 1 << (n % 8)
        vals = "|".join(f"{v:02x}" for v in range(256) if bool(v & bit) == on)
        self.expect(rf"\w+: ({vals})$", f"peek8 FLAGS+{n // 8:#x} 1")

    def count(self, addr, n, what):
        self.echo(f"{what}: {n}")
        self.expect(rf"{addr:08x}: {n:02x}$", f"peek8 {addr:#x} 1")

    def write(self, name):
        self.out("echo ALIVE")
        open(os.path.join(HERE, name), "w", newline="\n").write("\n".join(self.L) + "\n")
        print(f"{name}: {len(self.L)} lines")


def routes(p1, p2):
    """test command 49 op 8: the intro's entries for the lineup, player 1's line | player 2's << 8 (chamber_popo.lscript)"""
    return f"{(1 + p1) | (22 if p2 is None else 12 + p2) << 8:08x}"


def into_room(s, p2=True):
    """from the open area through the gate (all six lights out) into the hidden room: a real load (the actor's record)"""
    s.place(1028, 346, p2)
    s.out("frames 4", "keys 0x40", "waitmap 15 25 300", "keys 0", "frames 40")
    s.expect(r"map zone 15 area 25 ", "map")


def scene(s, shots=True):
    """the load's fade, then the scene: its walk-in, the pan, the lines, to the fight"""
    s.out("frames 60", f"waitnz {SCENE} 300")
    s.state(P_SCENE)
    if shots:
        for k in range(4):
            s.out("frames 70", f"shot {s.tag}_in{k}")
    s.out(f"stepz {SCENE} 60", "frames 30")


def fight_on(s, hp):
    s.echo("the fight: state 4, the door sealed (the beam shows), his HP, the first scene's flag")
    s.state(P_FIGHT)
    s.deco(0, 1)
    s.actor(1)
    s.popo_expect(6, f"{hp:08x}")
    s.flag(512, True)


def win_and_end(s, first, answer, items_before, two):
    """test command 7: his HP to 0 through his own OnHit (no dodge); the arms out, the end scene, the reward, the question"""
    s.echo("he stands in view (beside player 1) for the shot of his arms out")
    s.out("find PO 0x4F504F50", "deref B PO+8", "deref P1 0x03001FA8", "peek P1+0x158 2")
    s.place(200, 260, p2=two)
    s.out("poke32 B+0x158 0xF000", "poke32 B+0x15C 0x10400", "frames 2")
    s.cmd(7, 0, 0, 4)
    s.echo("HP 0: he does not fall; the bar goes, the arms out (state 5)")
    s.state(P_YIELD)
    s.out("frames 20", f"shot {s.tag}_yield", "frames 40")
    s.echo("the end scene: the flash, he stands at the far end facing them (an actor again, not the fighter)")
    s.state(P_OUTRO)
    s.out("frames 60", f"shot {s.tag}_far")
    s.actor(1)
    s.echo("on to the question: A through his line and the reward's pop-ups (the question arms CoopCall 18 before its box)")
    s.out("find CG 0xCE11CA3E", "stepnz CG+0x18 30")    # cellgames.c cg_state: +0x18 the question armed
    s.expect(r"\w+: 01$", "peek8 CG+0x18 1")
    s.out("frames 60", f"shot {s.tag}_ask")
    senzu, caps = items_before
    if first:
        s.echo("the first win: a Senzu bean and a +3 capsule of each; flag 513")
        s.count(SENZU, senzu + 1, "Senzu beans")
        for a, what in ((STR3, "Strength +3"), (PWR3, "Power +3"), (END3, "Endurance +3")):
            s.count(a, caps + 1, what)
        s.flag(513, True)
    else:
        s.echo("a later win: a Senzu bean, no capsules")
        s.count(SENZU, senzu + 1, "Senzu beans")
        s.count(STR3, caps, "Strength +3")
    s.out("key 1 6" if answer else "key 2 6", "frames 90", f"shot {s.tag}_answer", f"stepz {SCENE} 20", "frames 60")
    s.echo("the door is open again: state 7, the beam hidden")
    s.state(P_DONE)
    s.deco(0, 0)


def out_of_room(s, p2):
    s.place(244, 368, p2)
    s.out("frames 2", "keys 0x80", "waitmap 15 18 200", "keys 0", "frames 120")
    s.expect(r"map zone 15 area 18 var 1 player 10[0-4]\d,4[0-4]\d", "map")


def main_script():
    s = S(["Mr. Popo's hidden room behind the gate (docs/time-chamber.md 5 and 12.7), in one and two players and several lineups."])

    # ---- the way in: shut with five lights, open with six -------------------------------------------------------------
    s.begin("the gate: five lights out, no way through; six, the hidden room", PICCOLO, None)
    s.lights(0x1F)
    s.door()
    s.place(1028, 430, p2=False)
    s.out("keys 0x40", "frames 90", "keys 0")
    s.expect(r"map zone 15 area 18 var 1 player 10\d\d,(39\d|4[0-9]\d)", "map")
    s.lights(0x3F)
    s.door()
    into_room(s, p2=False)
    s.out("ents", "vram", "shot gate_in")
    s.echo("the room: his actor at the far end, back turned; the four jars; the door's beam hidden")
    s.actor(1)
    s.deco(0, 0)
    s.echo("loaded: the scene is about to start (1) or has (2)")
    s.out("find PO 0x4F504F50")
    s.expect(r"\w+: 0[12]", "peek8 PO+4 1")

    # ---- one player, Piccolo: the whole first visit -------------------------------------------------------------------
    s.echo("--- one player (Piccolo): the scene, his lines' routes, the seal, the hops, the autopilot's dodges, the win")
    s.tag = "one_piccolo"
    s.full()
    scene(s)
    fight_on(s, 5200)
    s.echo("the scene's routes for this lineup (test command 49 op 8: they run between scenes only)")
    s.popo_expect(8, routes(PICCOLO, None))
    s.out("ents", "vram", f"shot {s.tag}_fight")
    s.echo("the door sealed: walking down stops above it")
    s.place(244, 340, p2=False)
    s.out("keys 0x80", "frames 40", "keys 0")
    s.expect(r"map zone 15 area 25 var 1 player 24\d,3[45]\d", "map")
    s.echo("too close: he hops far (96 px or more from the player)")
    s.out("find PO 0x4F504F50", "deref B PO+8", "poke32 B+0x158 0xF400", "poke32 B+0x15C 0x13000", "frames 2")
    s.popo(3)
    s.out(f"peek {ARG} 1")
    s.out("frames 200")
    s.popo_expect(7, "(000000(6[0-9a-f]|[7-9a-f][0-9a-f])|00000[1-9a-f][0-9a-f]{2})")
    s.popo_expect(3, r"[0-9a-f]{4}000[1-9a-f]")
    s.out(f"shot {s.tag}_hop")
    s.echo("twelve punches from beside him (test command 27 op 6, kit 0): some land, about a third of the rest miss (dodged)")
    for _ in range(12):
        s.out(f"poke32 {ARG} 0x06000001", f"poke32 {CMD} 27", "frames 50")
    s.echo("the autopilot punches for 1800 frames: some punches land, some miss (dodged), he keeps away")
    s.full()
    s.popo(2, 1)
    s.out("frames 300", f"shot {s.tag}_bot", "frames 600")
    s.full()
    s.out("frames 900")
    s.full()
    s.popo(2, 0)
    s.popo(3)
    s.out(f"peek {ARG} 1")
    s.popo(5)
    s.out(f"peek {ARG} 1")
    s.echo("his HP is under his max (punches landed) and he dodged at least once")
    s.expect(r"0203fd0c: (?!1450)[0-9a-f]{4}[0-9a-f]{4}", f"peek {ARG} 1")
    s.popo_expect(3, r"000[1-9a-f][0-9a-f]{4}")
    win_and_end(s, True, False, (0, 0), False)
    s.echo("answered no: the lights stay out, no time round")
    s.expect(r"\w+: 3f$", "peek8 FLAGS+0x3F 1")
    s.popo_expect(0, r"000[37]0007")
    out_of_room(s, p2=False)

    s.echo("--- a later visit (one line and the fight), won, answered yes: the loop")
    s.tag = "again"
    s.full()
    into_room(s, p2=False)
    s.out("frames 60", f"waitnz {SCENE} 300", "frames 60", f"shot {s.tag}_line")
    s.state(P_SCENE)
    s.out(f"stepz {SCENE} 20", "frames 30")
    fight_on(s, 5200)
    win_and_end(s, False, True, (1, 1), False)
    s.echo("answered yes: the six lights back on, time round 1 (flag 520)")
    s.expect(r"\w+: 00$", "peek8 FLAGS+0x3F 1")
    s.flag(520, True)
    s.popo_expect(0, r"000[37]0107")
    out_of_room(s, p2=False)
    s.echo("outside: the gate's lights and beams stand again at the next load, the way shut")
    s.out("frames 60")
    for i in range(9):
        s.deco(i, 1)
    s.out(f"shot {s.tag}_gate")

    # ---- two players: Goku + Hercule, the lone boss's HP --------------------------------------------------------------
    s.begin("two players: Goku and Hercule, the lone boss's HP (180 %), the win by the autopilot", GOKU, HERCULE, "two_goku")
    s.lights(0x3F)
    s.door()
    s.full()
    into_room(s)
    scene(s)
    fight_on(s, 9360)
    s.popo_expect(8, routes(GOKU, HERCULE))
    s.out("ents", f"shot {s.tag}_fight")
    s.echo("the autopilot fights to the end (at most 3600 frames); HP 1 first so that the end comes in this test's time")
    s.full()
    s.popo(1, 0x80000000 | 5)
    s.popo(2, 1)
    s.out("frames 600")
    s.full()
    s.out("frames 600")
    s.full()
    s.out("frames 600")
    s.full()
    s.popo(2, 0)
    s.state(P_YIELD + 1)                            # the arms out are 40 frames: by now the end scene
    s.actor(1)
    s.out(f"stepz {SCENE} 30", "frames 60")
    s.state(P_DONE)
    s.out(f"shot {s.tag}_done")

    # ---- more lineups: the scene's routes and bodies -------------------------------------------------------------------
    for tag, p1, p2 in (("hercule_vegeta", HERCULE, VEGETA), ("krillin_alone", KRILLIN, None), ("gohan_piccolo", GOHAN, PICCOLO),
                        ("trunks_krillin", TRUNKS, KRILLIN), ("vegeta_goku", VEGETA, GOKU)):
        s.begin(f"lineup {tag}: the scene and the fight's start", p1, p2, tag)
        s.lights(0x3F)
        s.door()
        s.full()
        into_room(s, p2=p2 is not None)
        scene(s)
        fight_on(s, 9360 if p2 is not None else 5200)
        s.popo_expect(8, routes(p1, p2))
        s.out("ents")

    # ---- round 2: Popo and a room a step stronger; the rooms' prizes ---------------------------------------------------
    s.begin("time round 2: Popo at rating 600 (7000 HP alone)", PICCOLO, None)
    s.popo(4, 2)
    s.lights(0x3F)
    s.door()
    s.full()
    into_room(s, p2=False)
    scene(s, shots=False)
    fight_on(s, 7000)

    s.begin("a room's prize: Roshi's first win pays a Strength +3 capsule (flag 514); round 1: Roshi at rating 400 (3400 HP)", PICCOLO, None)
    s.popo(4, 1)
    s.lights(0)
    s.door()
    s.full()
    room_win(s, 3400)
    s.count(STR3, 1, "Strength +3 (the room's first win)")
    s.count(SENZU, 0, "Senzu beans")
    s.flag(514, True)

    s.begin("a room won again once round (flag 514 already set): a Senzu bean", PICCOLO, None)
    s.popo(4, 1)
    s.lights(0)
    s.out("flags +514")
    s.door()
    s.full()
    room_win(s, 3400)
    s.count(SENZU, 1, "Senzu beans")
    s.count(STR3, 0, "Strength +3")

    # ---- the big jars --------------------------------------------------------------------------------------------------
    s.begin("the big jars: both players full, nothing; player 2 hurt and out of ki: 30 % food and 30 % energy", PICCOLO, HERCULE, "jars")
    s.lights(0x3F)
    s.door()
    s.full()
    into_room(s)
    scene(s, shots=False)                            # (the fight starts: the jars are the same during it)
    s.full()
    s.place(40, 64)
    s.out("frames 4", "keys 0x40", "frames 4", "keys 0", "key 1 6", "frames 30", "key 1 6", "frames 30", "key 1 6", "frames 60")
    s.expect(r"findent IT = 00000000", "findent IT 0x08024C90")
    s.out(f"poke16 {entry(HERCULE):#x} 100", f"poke16 {entry(HERCULE) + 4:#x} 10")
    s.place(440, 64)
    s.out("frames 4", "keys 0x40", "frames 4", "keys 0", "key 1 6", "frames 30", "key 1 6", "frames 30", "key 1 6", "frames 20")
    s.out("shot jar_drop", "ents")
    s.echo("player 1 full, player 2 hurt and out of ki: both drop (player 2's bars), he walks over them: 30 % of 9999 HP and of 400 ki back")
    s.place(440, 40)
    s.out("frames 10")
    s.place(440, 48)
    s.out("frames 30")
    s.expect(r"\w+: (?!0064)[0-9a-f]{4}$", f"peek16 {entry(HERCULE):#x} 1")
    s.expect(r"\w+: (?!000a)[0-9a-f]{4}$", f"peek16 {entry(HERCULE) + 4:#x} 1")
    s.write("chamber_popo.txt")


def room_win(s, hp):
    """Roshi's dojo alone (chamber_gen.py's recipe): the intro, his HP, a win by test command 7, the lever and its cut-away"""
    s.place(1616, 1752, p2=False)
    s.out("frames 4", "keys 0x40", "waitmap 15 19 200", "keys 0", "frames 60")
    s.place(140, 215, p2=False)
    s.out("frames 4", "keys 0x40", "frames 60", "keys 0", "frames 110", f"stepz {SCENE} 40", "frames 90")
    s.out("find CH 0x4348414D", "deref B0 CH+8")
    s.echo(f"Roshi's HP: {hp}")
    s.expect(rf"\w+: 0*{hp:x}$", "peek B0+0x188 1")
    s.out(f"poke32 {CMD} 7", "frames 100", f"stepz {SCENE} 8", "frames 60")
    s.place(136, 96, p2=False)
    s.out("frames 4", "keys 0x40", "frames 6", "keys 0", "key 1 4", "waitmap 15 18 300", "frames 500", f"shot {s.tag}_prize",
          f"stepz {SCENE} 20", "mash 2 90", "frames 60")
    s.expect(r"map zone 15 area 19 ", "map")


def balance():
    s = S(["The balance numbers (docs/time-chamber.md 12.7): the test autopilot (both players walk up and punch, no dodging, no abilities)",
           "against Popo at round 0 and 2, two players and one, the Map Test party (level about 40, the wait's top) on its own full bars.",
           "Every 300 frames:",
           "test command 49 op 5 (frames | his HP << 16) and both players' HP. Not self-checking; read the log."])
    for tag, p1, p2, rnd in (("bal_two_r0", PICCOLO, HERCULE, 0), ("bal_one_r0", PICCOLO, None, 0), ("bal_two_r2", PICCOLO, HERCULE, 2),
                             ("bal_one_goku", GOKU, None, 0)):
        s.begin(tag, p1, p2)
        s.popo(4, rnd)
        s.lights(0x3F)
        s.door()
        into_room(s, p2=p2 is not None)
        s.out("frames 60", f"waitnz {SCENE} 300", f"stepz {SCENE} 60", "frames 30")
        s.popo(6)
        s.out(f"peek {ARG} 1")
        s.popo(2, 1)
        for k in range(24):
            s.out("frames 300")
            s.popo(5)
            s.out(f"peek {ARG} 1", f"peek16 {entry(p1):#x} 1")
            if p2 is not None:
                s.out(f"peek16 {entry(p2):#x} 1")
        s.popo(3)
        s.out(f"peek {ARG} 1", f"shot {tag}_end")
    s.write("chamber_popo_bal.txt")


if __name__ == "__main__":
    if "--balance" in sys.argv:
        balance()
    else:
        main_script()
