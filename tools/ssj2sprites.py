"""Super Saiyan 2 Gohan's playable record: the stock record 58 with the player groups it lacks, built from
the ROM at build time (docs/sprites.md "Super Saiyan 2 Gohan"). Emits C source compiled into the co-op ROM;
nothing from the ROM is committed.

usage: ssj2sprites.py roms/log2.gba build/gen/ssj2_sprites_data.c [--preview-dir build/x]

The stock game shows sprite 58 (Super Saiyan 2 Gohan, purple gi) only as player 1 in the last two Cell
Games fights (SetCharacterTransformation 0, 58 -> display row 4). Its record holds 19 groups with 9, 10,
11, 12, 14, 15 and 17 empty, so as a party member he would have no hurt pose (11), no lying pose (12, the
knock-out) and no tumble (20, past the group count). Super Saiyan teen Gohan (59, row 5) wears the same gi
on the same body and frame boxes, so ssj2_record is record 58 with:
  * header: 58's own (collision boxes), group count 19 -> 21;
  * groups 0-8, 13, 16, 18: 58's own descriptor arrays, by ROM address (nothing copied);
  * groups 11, 12, 20: 59's arrays, by ROM address (Super Saiyan 1 hair on those frames: they show for a
    few frames at a time);
  * groups 9, 10, 14, 15, 17, 19: empty, as in Super Saiyan Goku's record (61): no transformation,
    Spirit Bomb, fidget or halo poses.
The Makefile repoints id 58 at it in the relocated sprite index (spriteclone.py --extra 58=ssj2_record),
so the stock Cell Games scenes get the filled groups too. Preview: ssj2_gohan_preview.png (every group,
first frame per facing, ssj2_record above sprite 59).
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import sprites as S  # noqa: E402

SSJ2, SSJ1 = 58, 59
GROUP_COUNT = 21
FROM_SSJ1 = (11, 12, 20)                # hurt, lying, tumble
EMPTY = (9, 10, 14, 15, 17, 19)


def build(sp):
    """[21][4] descriptor array addresses (0 = empty)."""
    rom = sp.rom
    r58, r59 = sp.record(SSJ2), sp.record(SSJ1)
    g58, g59 = sp.groups(r58), sp.groups(r59)
    assert len(g58) == rom[r58 - S.ROM_BASE + 2] == 19, "record 58 changed?"
    assert all(not any(g58[gi]) for gi in (9, 10, 11, 12, 14, 15, 17)), "record 58 groups changed?"
    groups = []
    for gi in range(GROUP_COUNT):
        if gi in FROM_SSJ1:
            assert all(g59[gi]), f"sprite 59 group {gi} missing"
            groups.append(list(g59[gi]))
        elif gi in EMPTY:
            groups.append([0, 0, 0, 0])
        else:
            assert all(g58[gi]), f"sprite 58 group {gi} missing"
            groups.append(list(g58[gi]))
    return groups


def write_c(path, sp, groups):
    rom = sp.rom
    rec = sp.record(SSJ2)
    header = bytearray(rom[rec - S.ROM_BASE:rec - S.ROM_BASE + 0x4C])
    header[2] = GROUP_COUNT
    lines = ["/* generated by tools/ssj2sprites.py from the ROM: Super Saiyan 2 Gohan's record 58 with groups 11,",
             " * 12 and 20 from Super Saiyan Gohan's record 59. Build output only; never commit. */",
             '#include "rom.h"', "",
             "typedef struct { signed char xo, yo; u8 w, h; u32 attr; const void *blob; } S2Desc;",
             f"typedef struct {{ u8 header[0x4C]; const S2Desc *groups[{GROUP_COUNT}][4]; u32 end; }} S2Record;"]
    grp = ["{" + ", ".join(f"(const S2Desc *)0x{p:08x}u" for p in g) + "}" for g in groups]
    hdr = ", ".join(f"0x{b:02x}" for b in header)
    lines.append(f"const S2Record ssj2_record = {{{{{hdr}}}, {{{', '.join(grp)}}}, 0}};")
    os.makedirs(os.path.dirname(path) or ".", exist_ok=True)
    open(path, "w", encoding="utf-8", newline="\n").write("\n".join(lines) + "\n")


def preview(path, sp, groups):
    cell = 36
    rows = [("58+", groups), ("59", sp.groups(sp.record(SSJ1)))]
    cv = S.Canvas(28 + GROUP_COUNT * (cell + 2), len(rows) * 4 * (cell + 2) + 4, (60, 60, 90))
    for ri, (label, gs) in enumerate(rows):
        for d in range(4):
            y0 = 2 + (ri * 4 + d) * (cell + 2)
            cv.text(1, y0 + 2, label, (255, 255, 0))
            for gi in range(min(GROUP_COUNT, len(gs))):
                arr = gs[gi][d]
                if ri == 0 and d == 0:
                    cv.text(28 + gi * (cell + 2), 0, str(gi), (200, 200, 200))
                if not arr:
                    continue
                f = sp.frame_pixels(arr, 0)
                if not f:
                    continue
                xo, yo, w, h, attr, _ = sp.descriptor(arr, 0)
                px = f[2]
                flip = bool(attr & 0x10000000)
                x0 = 28 + gi * (cell + 2) + 2 + (8 + xo if w < 32 else 0)
                for y, line in enumerate(px):
                    for x, v in enumerate(line):
                        if v:
                            cv.put(x0 + ((w - 1 - x) if flip else x), y0 + 4 + y, sp.pal[v])
    cv.save(path)


def main():
    rom = open(sys.argv[1], "rb").read()
    out_c = sys.argv[2]
    pdir = sys.argv[sys.argv.index("--preview-dir") + 1] if "--preview-dir" in sys.argv else None
    sp = S.Sprites(rom)
    groups = build(sp)
    write_c(out_c, sp, groups)
    if pdir:
        os.makedirs(pdir, exist_ok=True)
        preview(os.path.join(pdir, "ssj2_gohan_preview.png"), sp, groups)
    print(f"wrote {out_c}: ssj2_record (sprite 58, {GROUP_COUNT} groups, {', '.join(map(str, FROM_SSJ1))} from 59)")


if __name__ == "__main__":
    main()
