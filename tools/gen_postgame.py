import re

def load(path):
    seqs, cur, ent = {}, None, None
    for line in open(path, encoding="utf-8"):
        line = line.rstrip("\n")
        m = re.match(r"^sequence (\S+) @(\w+)", line)
        if m:
            cur = {"addr": m.group(2), "entries": {}}
            seqs[m.group(1)] = cur
            ent = None
            continue
        if line == "end":
            cur = ent = None
            continue
        if cur is None:
            continue
        m = re.match(r"^  \[(\d+)\] (\w+)", line)
        if m:
            ent = int(m.group(1))
            cur["entries"][ent] = {"kind": m.group(2), "head": line, "body": []}
            continue
        if ent is not None and (line.startswith("        ") or re.match(r"^      \w+:$", line)):
            cur["entries"][ent]["body"].append(line.strip())
    return seqs

