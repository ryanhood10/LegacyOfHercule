"""Generate data/story/postgame.lscript (docs/story.md 4i) from the stock scenes plus our edits.

The Lookout after the Cell Games: Dende's talk scene (record 4 of map 261, zone 9 area 1) branches on the
post-game flags: the wishes (the first unchanged, the second Yamcha's slip), the explosion in the Arctic and
18 leaving; then, until Super 13 is beaten, Dende points north; after it, the finale on the Lookout; from then
on his question about starting the Buu's Fury campaign (CoopCall 18, a yes / no question), whose yes plays the
ending: Hercule's talk show, the credits and the rewritten epilogue (old Hercule beat the future Androids).

    python tools/script_asm.py dump map 9 1 > build/story/z9a1.lscript
    python tools/script_asm.py dump seq 0x083b8140 > build/story/epilogue.lscript
    python tools/script_asm.py dump seq 0x083c4e98 > build/story/talkshow.lscript
    python -I tools/gen_postgame.py              # from the repo root; rewrites data/story/postgame.lscript

Edit the chapter here, not in the .lscript."""
import re

def load(path):
    seqs, cur, ent = {}, None, None
    for line in open(path, encoding="utf-8"):
        line = line.rstrip("\n")
        m = re.match(r"^sequence (\S+) @(\w+)", line)
        if m:
            cur = {"addr": m.group(2), "entries": {}}
            seqs[m.group(1)] = cur
            ent = None
            continue
        if line == "end":
            cur = ent = None
            continue
        if cur is None:
            continue
        m = re.match(r"^  \[(\d+)\] (\w+)", line)
        if m:
            ent = int(m.group(1))
            cur["entries"][ent] = {"kind": m.group(2), "head": line, "body": []}
            continue
        if ent is not None and (line.startswith("        ") or re.match(r"^      \w+:$", line)):
            cur["entries"][ent]["body"].append(line.strip())
    return seqs

LK = load("build/story/z9a1.lscript")
EP = load("build/story/epilogue.lscript")
TS = load("build/story/talkshow.lscript")
WISH = LK["m261_r4_talk"]
EPI = EP["seq_083b8140"]
SHOW = TS["seq_083c4e98"]

def body(seq, idx):
    return list(seq["entries"][idx]["body"])

def addr_of(seq, idx):
    return seq["entries"][idx]["head"].split("@")[1].split()[0]

# post-game flags (docs/ids.md: 480-499; the arctic route owns 381 open / 382 Super 13 beaten)
F_WISHED, F_FINALE = 480, 483
F_ARCTIC_OPEN, F_13_BEATEN = 381, 382

out = []
entries = 0          # entries emitted in the current sequence (for the branch scripts' absolute indexes)
labels = {}

def emit(s=""):
    out.append(s)

def label(name):
    labels[name] = entries

def script(lines, comment=""):
    global entries
    emit("  script" + (f"                                 ; {comment}" if comment else ""))
    for l in lines:
        emit(("      " if re.match(r"^\w+:$", l) else "        ") + l)
    entries += 1

def text(speaker, s):
    global entries
    emit(f'  text {speaker} "{s}"')
    entries += 1

def stock(seq, idx, comment=""):
    global entries
    emit(f"  stock @{addr_of(seq, idx)}" + (f"    ; {comment}" if comment else ""))
    entries += 1

def stockseq(seq, a, b, comment=""):
    global entries
    emit(f"  stockseq @{seq['addr']} {a} {b}" + (f"    ; {comment}" if comment else ""))
    entries += b - a + 1

def stop():
    global entries
    emit("  stop 0x0")
    entries += 1

# Two passes: the branch script needs the sections' indexes, known after the first pass.
for pass_no in (1, 2):
    out.clear()
    entries = 0
    found = dict(labels)
    L = lambda n: found.get(n, 0)
    emit("; GENERATED by tools/gen_postgame.py from the stock dumps: edit the generator, not this file.")
    emit("; The Lookout after the Cell Games (docs/story.md 4i): Dende's talk scene, record 4 of map 261.")
    emit("; Flags: 480 the wishes are made (the post-game is on), 381 the Arctic open (its world-map landing and star),")
    emit("; 382 Super 13 beaten (set by the arctic summit's scene), 483 the finale seen (Dende asks about Buu's Fury).")
    emit("")
    emit("sequence pg_dende")
    script([f"StackTestStoryFlag {F_FINALE}", "JumpIfFalse L1", f"PushByte {L('prompt')}", "END", "L1:",
            f"StackTestStoryFlag {F_13_BEATEN}", "JumpIfFalse L2", f"PushByte {L('finale')}", "END", "L2:",
            f"StackTestStoryFlag {F_WISHED}", "JumpIfFalse L3", f"PushByte {L('north')}", "END", "L3:",
            f"PushByte {L('wish')}", "END"], "which part of the post-game")
    # ---- the wishes -----------------------------------------------------------------------------------
    label("wish")
    stock(WISH, 0, "the scene moves to the Lookout's edge (zone 9 area 7)")
    stockseq(WISH, 1, 44, "Dende heals Gohan, Krillin and 18, Shenron, the first wish, Goku stays dead, \"ONE WISH REMAINING\"")
    text(73, "KRILLIN: I have a wish...")
    script(["WaitFrames 20"])
    text(114, "YAMCHA: I wish we always had someone strong like Goku around!")
    script(body(WISH, 58), "stock entry 58: the wish is granted")
    text(93, "@YOUR WISH HAS BEEN GRANTED.\\x0bI MUST GO NOW.")
    script(body(WISH, 64), "stock entry 64: Shenron leaves")
    # Hercule at the TV station: the wish's mystery
    script(["FadeOut 120", "PushMulti 4, 20, 1, 16", "Negate", "WarpToMapNoEntities 88",
            "SpawnCharacterEntity 72, 120, 104", "SetEntityFacing 72, 0", "PanCameraToPosition 120, 88, 1",
            "FadeFromWhite 120", "WaitFrames 40", "SetEntityAnimation 72, 2"], "cut to Hercule at the TV station")
    text(67, "HERCULE: *grrrumble*\\x0bHuh?  Must've been something I ate!")
    script(["FadeOut 120", "DespawnEntity 72", "WarpToMapNoEntities 9, 7, 1, 144, 136", "DisableLayer 0", "DisableLayer 1",
            "SetEntityFacing 36, 3", "SetEntityFacing 11, 1", "FadeFromWhite 120", "WaitFrames 30",
            "ScreenShake 0, 20, 60", "PlayAudio 21", "SpawnCharacterEntity 24, 144, 232", "WalkToPosition 24, 136, 176",
            "SetEntityFacing 24, 1"], "back on the Lookout: an explosion, Bulma runs up")
    text(36, "BULMA: What was that explosion!?\\x0bDon't tell me you guys didn't finish off Cell!")
    text(90, "PICCOLO: No, I told you I no longer sense Cell!\\x0bThere was just a great pulse of power in the Arctic.")
    text(29, "ANDROID 18: It must be my brother.\\x0bI'm going to go check on him.")
    script(["PlayAudio 26", "FlyToPosition 11, 272, 136", "DespawnEntity 11"], "18 flies north (stock entry 72's flight)")
    text(90, "PICCOLO: We're all going.")
    script([f"SetStoryFlag {F_WISHED}", f"SetStoryFlag {F_ARCTIC_OPEN}", "FadeOut 120",
            "WarpToMapWithEntities 9, 1, 1, 792, 544", "SetPlayerVisible 1", "PlayAudio 62"], "the Arctic opens on the world map (its star)")
    text(0, "@^Journal Updated!")
    stop()
    # ---- until Super 13 is beaten --------------------------------------------------------------------
    label("north")
    text(46, "DENDE: That power in the Arctic...  someone has to stop it!")
    stop()
    # ---- the finale ----------------------------------------------------------------------------------
    label("finale")
    script(["FadeOut 120", "SetPlayerVisible 0", "WarpToMapNoEntities 9, 7, 1, 144, 136", "DisableLayer 0",
            "DisableLayer 1", "DespawnEntity 11", "SetEntityFacing 36, 3", "FadeFromWhite 120"], "back on the Lookout's edge, 18 gone")
    text(1, "Finally...  some time to relax.\\x0bNo more enemies to fight!")
    text(90, "PICCOLO: Peace...  for now.")
    stockseq(WISH, 75, 86, "the goodbyes: Tien and Yamcha leave, Piccolo stays, \"Goodbye Gohan!  Be sure to visit!\"")
    text(46, "DENDE: Talk to me if you want to discuss our times of peace!")
    script([f"SetStoryFlag {F_FINALE}", "FadeOut 120", "WarpToMapWithEntities 9, 1, 1, 792, 544", "SetPlayerVisible 1"],
           "the finale is seen: from now on Dende asks about Buu's Fury")
    stop()
    # ---- the question ----------------------------------------------------------------------------------
    label("prompt")
    script(["CoopCall 18, 1, 0, 0"], "arm the yes / no question (B answers no)")
    text(46, "DENDE: Enter Peace Times and start\\x0b\\\"Dragon Ball Z: Buu's Fury\\\" co-op?  (A: Yes  B: No)")
    script(["CoopCall 18, 0, 0, 0", "PushByte 1", "CmpEq", "JumpIfFalse L1", f"PushByte {L('sure')}", "END", "L1:",
            f"PushByte {L('notyet')}", "END"])
    label("notyet")
    text(46, "DENDE: Okay.  Come talk to me when you're ready!")
    stop()
    label("sure")
    script(["CoopCall 18, 1, 0, 0"])
    text(46, "Are you sure you want to start the Buu's Fury campaign?  (A: Yes  B: No)")
    script(["CoopCall 18, 0, 0, 0", "PushByte 1", "CmpEq", "JumpIfFalse L1", f"PushByte {L('ending')}", "END", "L1:",
            f"PushByte {L('notyet')}", "END"])
    # ---- the ending: the talk show, the credits, the new epilogue ----------------------------------------
    label("ending")
    b = body(SHOW, 0)
    b = [x for x in b if not x.startswith("WalkToPosition 0,")]   # the stock walk is to the studio's door in West City
    script(b, "stock entry 0 of the talk show without the walk to its door")
    stockseq(SHOW, 1, 28, "\"Late Night with Rob Howard\", Hercule's \"parlor tricks\", the crowd, the credits (flag 196)")
    b = body(EPI, 0)
    k = b.index("LoadMapWithEntities 1, 2, 1, 384, 552")
    b = b[:k + 1] + ["DespawnEntity 9", "DespawnEntity 11"] + b[k + 1:]
    b = [x for x in b if not x.startswith("SetEntityFacing 9,")]
    b = b[:-1] + ["SpawnCharacterEntity 158, 640, 520", "WalkToPosition 158, 560, 504", "SetEntityFacing 158, 2"] + b[-1:]
    script(b, "the epilogue's staging (stock entry 0): Trunks back in his time; no Androids; old Hercule walks up")
    text(101, "TRUNKS: I'm back.\\x0bNow I'm ready to take the Androids down!")
    text(67, "OLD HERCULE: Hey, Trunks!  You're too late!\\x0bI already beat them with my Megaton Punch while you were gone!")
    text(101, "TRUNKS: You...  what?!")
    text(67, "OLD HERCULE: I don't know what it is...\\x0bbut lately I feel stronger than I've ever been!")
    text(0, "@^The End.\\x0bThanks for playing!")
    script(["ReturnToTitleScreen"])
    emit("end")
    labels = dict(labels)

assert all(labels.get(k) == found.get(k) for k in labels), "indexes moved between passes"
open("data/story/postgame.lscript", "w", encoding="utf-8", newline="\n").write("\n".join(out) + "\n")
print(len(out), "lines", labels)
