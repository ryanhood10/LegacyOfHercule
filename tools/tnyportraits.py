"""The tournament's dialogue portraits imported from Buu's Fury (docs/tournament.md, docs/ids.md "Portraits"
140-189): each one is Buu's Fury's portrait module entry (0x086F393C) on LoG2's grey frame in LoG2's OBJ palette,
the way old Hercule's 126 is made (tools/oldherculeportrait.py `build`). Emits C: `tny_portrait_<id>` (a compressed
64x64 blob in the second ROM blob, TNY_ART) for krillinsprites.py --extra-portrait, and a preview sheet (Buu's
original left, ours right). Without the Buu ROM every id gets LoG2's stock Hercule portrait (67), so a build with
BUU=0 still links and no portrait id points at nothing. Build output only; never commit.

    python -I tools/tnyportraits.py roms/log2.gba build/gen/tny_portraits_data.c --buu roms/buu.gba|none
        [--preview build/tny_portraits.png] [--check BUILT.gba] 140=10 141=16 ...

--check reads a built ROM's portrait table the way the game's getter does (the literal at 0x0800BE10, word id + 1)
and asserts every listed id decodes to this portrait (the table wiring: krillinsprites.py --extra-portrait).
"""
import os
import struct
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import mapchunks as m  # noqa: E402
import sprites as S  # noqa: E402
import buu_sprites as BS  # noqa: E402
from buu2log2 import compress  # noqa: E402
from oldherculeportrait import build, BUU_PORTRAIT_MODULE, B  # noqa: E402

W = 64


def main():
    args = sys.argv[1:]
    rom, out = args[0], args[1]
    opts = {"--buu": "none", "--preview": None, "--check": None}
    pairs = []
    i = 2
    while i < len(args):
        if args[i] in opts:
            opts[args[i]] = args[i + 1]
            i += 2
        else:
            pid, bid = (int(x) for x in args[i].split("="))
            pairs.append((pid, bid))
            i += 1
    assert len({p for p, _ in pairs}) == len(pairs), "a portrait id is listed twice"
    log = open(rom, "rb").read()
    buu = open(opts["--buu"], "rb").read() if opts["--buu"] != "none" and os.path.exists(opts["--buu"]) else None
    lpal = S.Sprites(log).pal
    text = ["/* GENERATED by tools/tnyportraits.py: the tournament's dialogue portraits from Buu's Fury" +
            ("" if buu else " (no Buu's Fury ROM: LoG2's Hercule for every id)") +
            ". Build output only; never commit. */", '#include "rom.h"']
    pics = []
    total = 0
    for pid, bid in pairs:
        pic = build(log, buu, bid)
        blob = compress(pic)
        assert m.decompress(blob, 8, 1)[:4096] == pic
        total += len(blob)
        pics.append((pid, bid, pic))
        rows = [", ".join(f"0x{b:02x}" for b in blob[k:k + 16]) for k in range(0, len(blob), 16)]
        text.append(f"const u8 tny_portrait_{pid}[{len(blob)}] __attribute__((aligned(4), section(\".rodata.art\"))) = {{\n    "
                    + ",\n    ".join(rows) + "\n};")
    if opts["--check"]:
        built = open(opts["--check"], "rb").read()
        word = lambda a: struct.unpack_from("<I", built, a - B)[0]   # noqa: E731
        table = word(0x0800BE10)
        for pid, bid, pic in pics:
            got = m.unpack(built, word(table + 4 * (pid + 1)))[:4096]
            assert got == pic, f"portrait {pid} does not load from {opts['--check']}"
        print(f"check: {len(pics)} portraits load from the table at {table:#x} in {opts['--check']}")
        return
    os.makedirs(os.path.dirname(out) or ".", exist_ok=True)
    open(out, "w", encoding="utf-8", newline="\n").write("\n".join(text) + "\n")
    if opts["--preview"]:
        bpal = [S.Sprites.rgb(c) for c in struct.unpack_from("<256H", buu, BS.PALETTE - B)] if buu else None
        cols = 4
        cw, ch = 2 * W + 24, W + 14
        cv = S.Canvas(cols * cw, ((len(pics) + cols - 1) // cols) * ch)
        for k, (pid, bid, pic) in enumerate(pics):
            x0, y0 = (k % cols) * cw, (k // cols) * ch
            cv.text(x0 + 2, y0 + 2, f"{pid}", (255, 255, 0))
            cv.text(x0 + W + 4, y0 + 2, f"{bid}", (0, 255, 255))
            if buu:
                src = m.unpack(buu, struct.unpack_from("<I", buu, BUU_PORTRAIT_MODULE - B + 4 * bid)[0])[:4096]
                for y in range(W):
                    for x in range(W):
                        if src[y * W + x]:
                            cv.put(x0 + 2 + x, y0 + 10 + y, bpal[src[y * W + x]])
            for y in range(W):
                for x in range(W):
                    if pic[y * W + x]:
                        cv.put(x0 + W + 8 + x, y0 + 10 + y, lpal[pic[y * W + x]])
        cv.save(opts["--preview"])
    print(f"wrote {out}: {len(pairs)} portraits, {total} bytes ({'Buu' if buu else 'stock 67'})")


if __name__ == "__main__":
    main()
