"""Generate build/gen/journal_data.c: the journal's quest table with our chapters' entries (never committed).

The journal (FUN_080049FC) walks one table of 16-byte quests: +0 icon (0 story, 1 and 2 side quests), +4 a
condition script for "completed", +8 one for "active", +0xC the text. A quest whose completed test is true goes
to the completed page; else, if its active test is true, to the active page, in table order (the first entry is
the top line). Each page holds 43 lines (the stock count): the completed page is full with the stock quests, so
our entries never complete: they show while active (start flag set, end flag clear) and then disappear.

The patch (data/hercule.json "patches") points the table literal at 0x08004C80 to `journal_quests` and the
loop's `cmp r6, #43` at 0x08004AE2 to the new count (JOURNAL_COUNT below, asserted against the table).

    python -I tools/gen_journal.py roms/log2.gba build/gen/journal_data.c
"""
import struct
import sys

sys.path.insert(0, "tools")
import script_asm as S

JOURNAL_COUNT = 50          # keep in step with the "cmp r6" patch in data/hercule.json (bytes "322e")
STORY, SIDE = 0, 1

# Our entries, latest story first (the active page lists them above the stock ones). (icon, active condition, text)
# Conditions: "+N" flag N set, "-N" flag N clear, all of them must hold. Text: at most about 62 characters.
NEW = [
    (STORY, "+483", "Talk to Dende when you're ready to enter Peace Times"),
    (STORY, "+382 -483", "Return to Dende on the Lookout"),
    (STORY, "+381 -382", "Find the source of the power in the Arctic"),
    (SIDE, "+401 -402", "Defeat Broly on New Planet Vegeta"),
    (SIDE, "+400 -401", "Bring Vegeta to the ship behind Capsule Corporation"),
    (STORY, "+420 -421", "Go with Android 16 to Dr. Gero's lab and stop his computer"),
    (STORY, "+157 -420", "See Dr. Briefs in his workshop at Capsule Corporation"),
]
# Stock entries whose active test changes: quest 0 "Talk to Dende on the Lookout" (flag 195, Cell beaten) never
# completes in the stock game; here it ends with the wishes (480), when the post-game's entries take over. Quest 1
# "Enter the Cell Games" waits for the Gero chapter too (421), as the arena's landing does.
STOCK_ACTIVE = {0: "+195 -480", 1: "+191 +421"}


def cond_bytes(spec):
    lines = [] if spec else ["PushByte 0"]          # an empty condition: never
    for k, tok in enumerate(spec.split()):
        lines.append(("StackTestStoryFlag " if tok[0] == "+" else "StackTestStoryFlagNot ") + tok[1:])
        if k:
            lines.append("And")
    text = "script c\n" + "\n".join("    " + l for l in lines) + "\n    END\nend\n"
    return S.assemble_script(S.parse_file(text)["c"]["items"])


def c_bytes(b):
    return "{ " + ", ".join(f"0x{x:02x}" for x in b) + " }"


def c_str(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main(rom_path, out_path):
    rom = open(rom_path, "rb").read()
    base = S.off(S.QUEST_TABLE)
    stock = [struct.unpack_from("<IIII", rom, base + 16 * q) for q in range(S.QUEST_COUNT)]
    assert struct.unpack_from("<I", rom, 0x4C80)[0] == S.QUEST_TABLE, "the journal's table literal moved"
    assert rom[0x4AE2:0x4AE4] == bytes([S.QUEST_COUNT, 0x2E]), "the journal's loop count moved"
    rows, conds = [], []

    def cond(spec):
        conds.append(f"static const u8 jc{len(conds)}[] = {c_bytes(cond_bytes(spec))};   // {spec or 'never'}")
        return f"jc{len(conds) - 1}"

    never = cond("")
    for icon, spec, text in NEW:
        assert len(text) <= 62, text
        rows.append(f"    {{ {icon}, {{ 0, 0, 0 }}, {never}, {cond(spec)}, {c_str(text)} }},")
    for q, (w0, done, active, text) in enumerate(stock):
        a = cond(STOCK_ACTIVE[q]) if q in STOCK_ACTIVE else f"(const u8 *)0x{active:08X}"
        rows.append(f"    {{ {w0 & 0xFF}, {{ 0, 0, 0 }}, (const u8 *)0x{done:08X}, {a}, (const char *)0x{text:08X} }},"
                    f"   // stock {q}")
    assert len(rows) == JOURNAL_COUNT, f"{len(rows)} quests: update JOURNAL_COUNT and the cmp patch"
    assert JOURNAL_COUNT <= 255
    out = ["/* GENERATED by tools/gen_journal.py: the journal's quest table, stock quests plus ours. Build output only;",
           " * never commit (it holds addresses read from the ROM). */",
           '#include "rom.h"',
           "typedef struct JournalQuest { u8 icon, pad[3]; const u8 *done, *active; const char *text; } JournalQuest;"]
    out += conds
    out += [f"const JournalQuest journal_quests[{JOURNAL_COUNT}] = {{"] + rows + ["};", ""]
    open(out_path, "w", encoding="utf-8", newline="\n").write("\n".join(out))
    print(f"wrote {out_path}: {JOURNAL_COUNT} quests ({len(NEW)} new)")


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
