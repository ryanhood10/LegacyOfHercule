"""Old Hercule's dialogue portrait (the future timeline's Hercule, docs/story.md: the prologue, Future Trunks' visit
and the epilogue): Buu's Fury's Hercule portrait (its portrait module 0x086F393C, id 76) on LoG2's grey frame,
remapped to LoG2's OBJ palette. Both games keep portraits as 64x64 linear 8bpp images in a kind-1 LZ blob. Without
the Buu's Fury ROM it is LoG2's own Hercule portrait (67) unchanged. Emits C (`old_hercule_portrait`, a compressed
blob) for krillinsprites.py --extra-portrait. Build output only; never commit.

    python -I tools/oldherculeportrait.py roms/log2.gba build/gen/oldherc_portrait_data.c --buu roms/buu.gba|none
"""
import os
import struct
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import mapchunks as m
import sprites as S
import buu_sprites as BS
from buu2log2 import compress, nearest_table

B = 0x08000000
BUU_PORTRAIT_MODULE = 0x086F393C   # word id = blob pointer (ids 0-7 zero); the getter's literal is at 0x08012194
BUU_HERCULE = 76                   # the Buu-saga Hercule (red cape)
LOG_TABLE = 0x083EC9D4             # Portrait_Table
LOG_HERCULE = 67
W = 64
BUU_FRAME = {0, 2, 28, 29, 30, 62, 63, 64, 109, 110}   # the gold frame's colours


def build(log, buu, buu_id=BUU_HERCULE):
    """LoG2-format 64x64 portrait (raw indices) of Buu's Fury portrait `buu_id` (stock 67 without the Buu ROM)."""
    ref = m.unpack(log, struct.unpack_from('<I', log, LOG_TABLE - B + 4 * LOG_HERCULE)[0])[:4096]
    if buu is None:
        return bytes(ref)
    bpal = [S.Sprites.rgb(c) for c in struct.unpack_from('<256H', buu, BS.PALETTE - B)]
    lpal = S.Sprites(log).pal
    src = m.unpack(buu, struct.unpack_from('<I', buu, BUU_PORTRAIT_MODULE - B + 4 * buu_id)[0])[:4096]
    # the gold frame: flood from the edge through its colours, within 5 px of the edge
    frame, stack = set(), [(y, x) for y in range(W) for x in range(W) if y in (0, W - 1) or x in (0, W - 1)]
    while stack:
        y, x = stack.pop()
        if (y, x) in frame or not (0 <= y < W and 0 <= x < W):
            continue
        if src[y * W + x] not in BUU_FRAME or min(y, x, W - 1 - y, W - 1 - x) > 5:
            continue
        frame.add((y, x))
        stack += [(y + 1, x), (y - 1, x), (y, x + 1), (y, x - 1)]
    # fill the frame's place by growing the picture outward
    pic = {(y, x): src[y * W + x] for y in range(W) for x in range(W) if (y, x) not in frame}
    while len(pic) < W * W:
        add = {}
        for y in range(W):
            for x in range(W):
                if (y, x) in pic:
                    continue
                for dy, dx in ((0, 1), (0, -1), (1, 0), (-1, 0)):
                    if (y + dy, x + dx) in pic:
                        add[(y, x)] = pic[(y + dy, x + dx)]
                        break
        pic.update(add)
    # LoG2's palette inside LoG2's own 3 px grey frame (portrait 67's)
    tbl = nearest_table(bpal, lpal)
    out = bytearray(ref)
    for y in range(3, W - 3):
        for x in range(3, W - 3):
            out[y * W + x] = tbl[pic[(y, x)]][0] or 1
    return bytes(out)


def main():
    rom, out = sys.argv[1], sys.argv[2]
    buu_path = sys.argv[sys.argv.index('--buu') + 1] if '--buu' in sys.argv else 'none'
    log = open(rom, 'rb').read()
    buu = open(buu_path, 'rb').read() if buu_path != 'none' and os.path.exists(buu_path) else None
    pic = build(log, buu)
    blob = compress(pic)
    assert m.decompress(blob, 8, 1)[:4096] == pic
    rows = [', '.join(f'0x{b:02x}' for b in blob[i:i + 16]) for i in range(0, len(blob), 16)]
    text = ('/* GENERATED by tools/oldherculeportrait.py: old Hercule\'s dialogue portrait (' +
            ('Buu\'s Fury\'s Hercule' if buu else 'LoG2\'s Hercule: no Buu\'s Fury ROM') +
            '). Build output only; never commit. */\n#include "rom.h"\n'
            f'const u8 old_hercule_portrait[{len(blob)}] __attribute__((aligned(4))) = {{\n    ' +
            ',\n    '.join(rows) + '\n};\n')
    open(out, 'w', encoding='utf-8', newline='\n').write(text)
    print(f'wrote {out}: portrait {len(blob)} bytes ({"Buu" if buu else "stock 67"})')


if __name__ == '__main__':
    main()
